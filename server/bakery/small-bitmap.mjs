/**
 * Prerender small size (`docs/plan/c10a-contract.md` Section 9; semantics in `product/rendering.md`
 * "Heavy pipeline: prerender" "two tiers").
 *
 * # Size [Contract Section 9, consistent with small-size assets]
 *
 * Scaled down proportionally to fit within 800×600 without upscaling, preserving the project
 * aspect ratio: scale ratio `s = min(1, 800 / projectWidth, 600 / projectHeight)`, pixel dimensions
 * rounded down (16:9 → 800×450, 9:16 → 337×600).
 *
 * An HTML snapshot is the subtree **inside a card's wrapper layer** (`src/render/createSnapshot.ts`:
 * records only the wrapper layer's innerHTML; position, opacity, and filters are generated by the
 * wrapper layer upon remounting), and the page mounts it on the snapshot plane with `inset: 0` inside
 * the wrapper layer. Therefore, the small bitmap renders the contents of the **wrapper layer's
 * box** (clip box w×h, `src/kernel/frameSize.mjs`), scaled by the same `s`: for cards without a box
 * set, the box is the entire stage, which corresponds exactly to the two examples above; the online
 * page fits it across the snapshot plane, occupying the same area as original-size HTML snapshots.
 *
 * # Generation [Contract Section 9]
 *
 * - **HTML snapshot**: in the render node's controlled stage (another frame-controlled page in
 *   prerender Chrome, export page `/?export=1`, with the same font replay environment as the
 *   original snapshot: same approach as `capture-snapshot.mjs`), place the snapshot HTML for this
 *   frame into a box-sized container, scale the whole thing by `scale(s)`, and capture as WebP
 *   (with alpha, quality 80). The original HTML snapshot remains unchanged.
 * - **PNG**: the full transparent stage image is scaled proportionally once, also outputting WebP
 *   (`renderSmallPng`).
 *
 * This module only handles "given an HTML snippet or a PNG, output a small bitmap"; when to generate
 * it, where to store it, and how to advance frames are managed by `frame-pipeline.mjs`.
 */
import { captureFrame } from './capture-frame.mjs';

export const SMALL_MAX_WIDTH = 800;
export const SMALL_MAX_HEIGHT = 600;
/** WebP quality (Contract Section 9 [ruling]) */
export const SMALL_WEBP_QUALITY = 80;
/** File name suffix of small bitmap in local frame store: `<localFrame>.small.webp`, same dir as `<localFrame>.html` */
export const SMALL_SUFFIX = '.small.webp';

/** Project aspect ratio → scale ratio (no upscaling) */
export function smallScale(projectWidth, projectHeight) {
  const w = Number(projectWidth), h = Number(projectHeight);
  if (!(w > 0) || !(h > 0)) return 1;
  return Math.min(1, SMALL_MAX_WIDTH / w, SMALL_MAX_HEIGHT / h);
}

/**
 * Pixel dimensions of a box scaled down by the project scale ratio (rounded down, at least 1).
 * `boxWidth` / `boxHeight` defaults to the entire stage (for cards without a box set).
 */
export function smallSize({ projectWidth, projectHeight, boxWidth = projectWidth, boxHeight = projectHeight }) {
  const scale = smallScale(projectWidth, projectHeight);
  const px = v => Math.max(1, Math.floor(Number(v) * scale + 1e-9));
  return { scale, width: px(boxWidth), height: px(boxHeight) };
}

/** WebP file header (RIFF....WEBP) */
export function isWebp(buf) {
  return !!buf && buf.length >= 12 && buf.toString('ascii', 0, 4) === 'RIFF' && buf.toString('ascii', 8, 12) === 'WEBP';
}

/** WebP pixel dimensions (recognizes VP8 / VP8L / VP8X headers); returns null if unrecognized */
export function webpSize(buf) {
  if (!isWebp(buf) || buf.length < 30) return null;
  const chunk = buf.toString('ascii', 12, 16);
  if (chunk === 'VP8X') return { width: 1 + buf.readUIntLE(24, 3), height: 1 + buf.readUIntLE(27, 3) };
  if (chunk === 'VP8L') {
    const b = buf.readUInt32LE(21);
    return { width: 1 + (b & 0x3fff), height: 1 + ((b >> 14) & 0x3fff) };
  }
  if (chunk === 'VP8 ') return { width: buf.readUInt16LE(26) & 0x3fff, height: buf.readUInt16LE(28) & 0x3fff };
  return null;
}

/**
 * Renderer for drawing small bitmaps on a frame-controlled page (`openExtraSession` in `chrome.mjs`
 * / prerender room itself). Used sequentially on the same page; `session` must have `page`,
 * `client`, and `beginFrame` (the items required by `captureFrame`).
 */
export function createSmallRenderer(session) {
  let viewport = null;
  const ensureViewport = async (width, height) => {
    if (viewport && viewport.width === width && viewport.height === height) return;
    await session.page.setViewport({ width, height, deviceScaleFactor: 1 });
    await session.client.send('Emulation.setDefaultBackgroundColorOverride', { color: { r: 0, g: 0, b: 0, a: 0 } });
    viewport = { width, height };
    // Pixels may not be present in the first few ticks after dimensions change (per `capture-frame.mjs`
    // note): skip one tick first
    await session.beginFrame?.({ screenshot: { format: 'jpeg', quality: 0 } }).catch(() => {});
  };
  const shoot = async (mount) => {
    await session.page.evaluate(mount.fn, mount.arg);
    try {
      return await captureFrame(session, { format: 'webp', quality: SMALL_WEBP_QUALITY });
    } finally {
      await session.page.evaluate(() => {
        document.getElementById('pc-small-bitmap')?.remove();
        const root = document.getElementById('root');
        if (root && root.dataset.pcSmallDisplay !== undefined) { root.style.display = root.dataset.pcSmallDisplay; delete root.dataset.pcSmallDisplay; }
      }).catch(() => {});
    }
  };
  return {
    /** One frame HTML snapshot → WebP. `boxWidth` / `boxHeight` are clip box (wrapper layer) dimensions */
    async renderHtml({ html, projectWidth, projectHeight, boxWidth = projectWidth, boxHeight = projectHeight }) {
      const size = smallSize({ projectWidth, projectHeight, boxWidth, boxHeight });
      await ensureViewport(size.width, size.height);
      return shoot({
        arg: { html: String(html ?? ''), w: Number(boxWidth), h: Number(boxHeight), s: size.scale },
        fn: ({ html: h, w, h: bh, s }) => {
          const root = document.getElementById('root');
          if (root && root.dataset.pcSmallDisplay === undefined) { root.dataset.pcSmallDisplay = root.style.display; root.style.display = 'none'; }
          const box = document.createElement('div');
          box.id = 'pc-small-bitmap';
          // Wrapper layer box: absolute positioning, box size, scaled down to small size as a whole.
          // The snapshot plane on the page is also an inset:0 layer inside the wrapper layer
          box.style.cssText = `position:absolute;left:0;top:0;width:${w}px;height:${bh}px;transform:scale(${s});transform-origin:0 0;isolation:isolate;overflow:visible`;
          const template = document.createElement('template');
          template.innerHTML = h;
          // Same sanitization as `capture-snapshot.mjs`: snapshots are data, not executable pages
          template.content.querySelectorAll('script,iframe,object,embed,base,meta,link').forEach(el => el.remove());
          for (const element of template.content.querySelectorAll('*')) {
            for (const attr of [...element.attributes]) {
              if (/^on/i.test(attr.name) || /^(?:javascript|vbscript):/i.test(attr.value.trim())) element.removeAttribute(attr.name);
            }
          }
          const plane = document.createElement('div');
          plane.style.cssText = 'position:absolute;inset:0';
          plane.appendChild(template.content);
          box.appendChild(plane);
          document.body.appendChild(box);
        },
      });
    },
    /** Full-stage PNG → WebP scaled proportionally once */
    async renderPng({ png, projectWidth, projectHeight }) {
      const size = smallSize({ projectWidth, projectHeight });
      await ensureViewport(size.width, size.height);
      const src = 'data:image/png;base64,' + Buffer.from(png).toString('base64');
      return shoot({
        arg: { src, w: size.width, h: size.height },
        fn: ({ src: url, w, h }) => {
          const root = document.getElementById('root');
          if (root && root.dataset.pcSmallDisplay === undefined) { root.dataset.pcSmallDisplay = root.style.display; root.style.display = 'none'; }
          const img = document.createElement('img');
          img.id = 'pc-small-bitmap';
          img.src = url;
          img.style.cssText = `position:absolute;left:0;top:0;width:${w}px;height:${h}px`;
          document.body.appendChild(img);
        },
      });
    },
  };
}
