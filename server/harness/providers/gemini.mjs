// Corresponds to claude-quickstarts/agents/providers/gemini.py
// Vendor API key points: GenerateContent endpoint, role is user/model, tools use
// functionDeclarations/functionCall/functionResponse, SSE parses candidates.
import { readSse, assertOk, STREAM_CUT, isCutReadError, streamCutNotice } from './base.mjs';
import { toolToVendor } from '../schema.mjs';
import { resolveMaxOutput, lowerOutputAfter400 } from '../model-limits.mjs';
import { noteOutputFallback, asRead } from './output-fallback.mjs';

export function createProvider(cfg, { fetchImpl = globalThis.fetch } = {}) {
  let toolUseCounter = 0;
  
  return {
    name: 'gemini',
    async *stream(messages, tools, system, signal) {
      let baseUrl = cfg.baseUrl || 'https://generativelanguage.googleapis.com';
      if (baseUrl.endsWith('/')) baseUrl = baseUrl.slice(0, -1);
      const url = `${baseUrl}/v1beta/models/${cfg.model}:streamGenerateContent?alt=sse`;

      const headers = {
        'x-goog-api-key': cfg.apiKey,
        'content-type': 'application/json'
      };

      const toolUseIdToName = new Map();
      for (const msg of messages) {
        if (msg.role === 'assistant' && Array.isArray(msg.content)) {
          for (const block of msg.content) {
            if (block.type === 'tool_use') {
              toolUseIdToName.set(block.id, block.name);
            }
          }
        }
      }

      const geminiMessages = [];
      for (const msg of messages) {
        if (msg.role === 'user') {
          if (!Array.isArray(msg.content)) continue;
          const parts = [];
          for (const block of msg.content) {
            if (block.type === 'text') {
              parts.push({ text: block.text });
            } else if (block.type === 'image') {
              parts.push({ inlineData: { mimeType: block.mime || 'image/png', data: block.data } });
            } else if (block.type === 'tool_result') {
              const name = toolUseIdToName.get(block.tool_use_id) || 'unknown';
              /*
               * `FunctionResponse.response` is a Struct in the protocol, meaning it **must be a JSON object**.
               * If it is already an object, send it as is; do not JSON.stringify it into a flat string:
               * flattening both burns extra tokens and wipes out nested hierarchy, forcing the model to re-parse
               * from the string itself.
               * null and arrays are not Structs and still need to be wrapped.
               */
              const c = block.content;
              const isStruct = c !== null && typeof c === 'object' && !Array.isArray(c);
              const fnResp = { name, response: isStruct ? c : { result: c } };
              // Only official IDs are sent back; synthetic gemini-call-N are generated by us, and it will not
              // recognize them if sent
              if (block.tool_use_id && !String(block.tool_use_id).startsWith('gemini-call-')) {
                fnResp.id = block.tool_use_id;
              }
              parts.push({ functionResponse: fnResp });
            }
          }
          geminiMessages.push({ role: 'user', parts });
        } else if (msg.role === 'assistant') {
          if (!Array.isArray(msg.content)) continue;
          const parts = [];
          for (const block of msg.content) {
            if (block.type === 'text') {
              parts.push({ text: block.text });
            } else if (block.type === 'tool_use') {
              parts.push({
                functionCall: {
                  name: block.name,
                  args: block.input || {}
                }
              });
            }
          }
          geminiMessages.push({ role: 'model', parts });
        }
      }

      // Per-request output limit is fetched by model (model-limits.mjs, A07 2026-10-22): 65536 for
      // gemini-2.5 and later; thoughts also count toward output
      let maxOutput = resolveMaxOutput(cfg);
      const body = {
        contents: geminiMessages,
        generationConfig: {
          maxOutputTokens: maxOutput
        }
      };

      /*
       * Thinking effort tier. Previously, **not a single character was sent** here: cfg.effort was passed
       * all the way from runners/api.mjs (openai.mjs sends it as reasoning_effort), but dropped entirely
       * here, so the thinking tier selected for Gemini on the panel had no effect whatsoever.
       *
       * `thinkingLevel` takes low / medium / high, matching the three tiers on the panel; pass through
       * directly without converting token counts yourself. If `includeThoughts` is not enabled, thought
       * summaries won't be received: the "What the model is thinking" bar in the UI will stay empty.
       */
      if (cfg.effort) {
        body.generationConfig.thinkingConfig = { thinkingLevel: cfg.effort, includeThoughts: true };
      }

      if (system) {
        body.systemInstruction = {
          parts: [{ text: system }]
        };
      }

      const geminiTools = (tools || []).map(t => toolToVendor(t, 'gemini', { compat: cfg.schemaCompat }));
      if (geminiTools.length > 0) {
        body.tools = [{ functionDeclarations: geminiTools }];
      }

      /** Timestamp of the last actual request (used for elapsed time when capping by speed, see harness/output-speed.mjs) */
      let sentAt = Date.now();
      const post = (b) => { sentAt = Date.now(); return fetchImpl(url, { method: 'POST', headers, body: JSON.stringify(b), signal }); };

      let response = await post(body);

      /*
       * Older models do not recognize thinkingConfig and return 400 immediately if passed: that would
       * mean a user selecting a thinking tier on the panel kills the entire chat turn, and the error only
       * says a field is unrecognized, so no one would connect it to that dropdown. Therefore, on 400,
       * strip it and resend once: losing the thinking tier is better than leaving the chat stuck in red.
       * (Same reasoning as the "strip and resend if thinking tier + tools are rejected" block in
       * openai.mjs.)
       */
      let sent = body;
      if (response.status === 400) {
        let text = '';
        try { text = await response.text(); } catch { /* If it cannot be read, assume it is not */ }
        response = asRead(response, text);
        // First check whether the output limit is too large (A07): if so, drop down one tier, resend once,
        // and log it; if not, follow the original behavior of stripping the thinking tier and resending
        const lower = lowerOutputAfter400(text, maxOutput);
        if (lower) {
          yield noteOutputFallback({ vendor: 'gemini', model: cfg.model, action: 'lower', from: maxOutput, to: lower });
          maxOutput = lower;
          sent = { ...body, generationConfig: { ...body.generationConfig, maxOutputTokens: lower } };
          response = await post(sent);
          if (response.status === 400) { try { text = await response.text(); } catch { text = ''; } response = asRead(response, text); }
        }
        if (response.status === 400 && sent.generationConfig.thinkingConfig) {
          const retry = { ...sent, generationConfig: { ...sent.generationConfig } };
          delete retry.generationConfig.thinkingConfig;
          response = await post(retry);
        }
      }

      await assertOk(response, 'gemini');
      yield { type: 'response_open', sentAt };

      let promptTokens = 0;
      let candidatesTokens = 0;
      let thoughtsTokens = 0;
      let stopReason = null;
      let sawCandidate = false;
      /** Stream emitted content (text, thoughts, tool calls): if cut later, finalize as truncated (STREAM_CUT), see base.mjs */
      let started = false;
      /** Stream disconnected before finishReason: { how, detail } */
      let cut = null;

      try {
      for await (const { event, data } of readSse(response, { signal })) {
        if (!data || data === '[DONE]') continue;
        let parsed;
        try {
          parsed = JSON.parse(data);
        } catch {
          continue;
        }

        if (event === 'error' || parsed.type === 'error' || parsed.error) {
          const message = typeof parsed.error === 'string' ? parsed.error : (parsed.error?.message || parsed.message || 'API stream returned an error');
          if (stopReason) break; // Already finalized normally; subsequent errors do not affect this reply
          // Errors arriving after stream already emitted content (gateway cut off midway): finalize as
          // truncated, preserving already-received text and tool calls that arrived as a whole block
          if (!started) throw new Error(message);
          cut = { how: 'error-event', detail: message };
          break;
        }

        const candidate = parsed.candidates?.[0];
        if (candidate) {
          sawCandidate = true;
          if (candidate.content?.parts?.length) started = true;
          if (candidate.content?.parts) {
            for (const part of candidate.content.parts) {
              /*
               * Thought content is a **regular text part marked with thought:true**, not a different kind
               * of part. Therefore, this branch must be checked before part.text, otherwise it will be hijacked
               * entirely by the text branch below: the symptom is that the model's thoughts are broadcast as
               * regular text, while the "What the model is thinking" column remains perpetually empty.
               */
              if (part.thought === true) {
                yield { type: 'thinking_delta', text: part.text || '' };
              } else if (part.text) {
                yield { type: 'text_delta', text: part.text };
              } else if (part.functionCall) {
                toolUseCounter++;
                /*
                 * Use the official ID if available. Synthetic `gemini-call-N` IDs are numbered in arrival order;
                 * when calling the same tool in parallel within a single turn, the returned functionResponse is
                 * paired only by name, so which matches which is pure luck: resulting in cross-wired tool results
                 * without any errors raised.
                 */
                const id = part.functionCall.id || `gemini-call-${toolUseCounter}`;
                yield { type: 'tool_use', id, name: part.functionCall.name, input: part.functionCall.args || {} };
              }
            }
          }
          if (candidate.finishReason) {
             stopReason = candidate.finishReason;
          }
        }

        if (parsed.usageMetadata) {
          if (parsed.usageMetadata.promptTokenCount !== undefined) {
             promptTokens = parsed.usageMetadata.promptTokenCount;
          }
          if (parsed.usageMetadata.candidatesTokenCount !== undefined) {
             candidatesTokens = parsed.usageMetadata.candidatesTokenCount;
          }
          // Thinking tokens are not in candidatesTokenCount and are reported separately; used only for
          // speed-based limit setting (output-speed.mjs), while usage still records only output
          if (parsed.usageMetadata.thoughtsTokenCount !== undefined) {
             thoughtsTokens = Number(parsed.usageMetadata.thoughtsTokenCount) || 0;
          }
        }
      }
      } catch (err) {
        // Connection cut midway through the stream: if it emitted content and has not finalized, finalize
        // as truncated; otherwise rethrow as usual
        if (!isCutReadError(err, signal) || (!started && !stopReason)) throw err;
        if (!stopReason) cut = { how: 'connection', detail: err?.message || String(err) };
      }

      if (!stopReason && !cut && started && !signal?.aborted) cut = { how: 'no-finish', detail: 'Stream ended before finishReason' };
      if (cut) {
        // Gemini tool calls arrive as whole blocks, with no half-written calls to preserve; already-received
        // calls execute as usual, and text is preserved
        yield streamCutNotice('gemini', cut.how, cut.detail);
        yield { type: 'usage', input: promptTokens, output: candidatesTokens, ...(thoughtsTokens ? { thoughts: thoughtsTokens } : {}) };
        yield { type: 'stop', reason: STREAM_CUT };
        return;
      }

      if (!sawCandidate && !stopReason && !signal?.aborted) {
        throw new Error('The API response stream ended early or returned no SSE data. Check the API protocol.');
      }

      yield { type: 'usage', input: promptTokens, output: candidatesTokens, ...(thoughtsTokens ? { thoughts: thoughtsTokens } : {}) };
      /*
       * Erroneous finalization cannot masquerade as normal completion. Previously, it uniformly yielded
       * 'stop', making the upper layer assume the turn finished properly: yet MALFORMED_FUNCTION_CALL
       * (model corrupted the tool call) and SAFETY / RECITATION (blocked) actually mean **nothing was
       * accomplished in this turn**. The consequence of masquerading is no indication on the UI, either
       * staying frozen or having the upper layer start another turn assuming "normal completion",
       * spinning in circles.
       *
       * Use throw instead of yielding an error event: the event loop in `harness/agent.mjs` only
       * recognizes five types: text_delta / thinking_delta / tool_use / stop / usage, with **no error
       * branch**: yielding it would be silently dropped, accomplishing nothing. Its outer try/catch
       * bubbles exceptions upward, and anthropic.mjs also throws on in-stream errors, so this stays
       * consistent with it.
       */
      if (stopReason && stopReason !== 'STOP' && stopReason !== 'MAX_TOKENS') {
        throw new Error(`Gemini did not finish this turn normally (finishReason: ${stopReason}).`
          + (stopReason === 'MALFORMED_FUNCTION_CALL' ? 'The model wrote a malformed tool call; retrying once usually fixes it.' : ''));
      }
      yield { type: 'stop', reason: stopReason || 'STOP' };
    }
  };
}
