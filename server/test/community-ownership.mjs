const CODE_EXT = new Set(['.ts', '.tsx', '.mjs', '.js', '.cjs']);
const SKIP_DIRS = new Set([
  'node_modules', '.git', 'dist', 'out', 'target', 'runtime', '.worktrees', '.claude', 'coverage',
]);

/** Traverses the repository and lists repository-relative paths (forward slashes) for all code files */
export function listCodeFiles(root) {
  const found = [];
  (function walk(dir) {
    let entries;
    try {
      entries = readdirSync(dir, { withFileTypes: true });
    } catch {
      return;
    }
    for (const e of entries) {
      if (e.name.startsWith('.') || SKIP_DIRS.has(e.name)) continue;
      const full = path.join(dir, e.name);
      if (e.isDirectory()) walk(full);
      else if (CODE_EXT.has(path.extname(e.name))) found.push(path.relative(root, full).split(path.sep).join('/'));
    }
  })(root);
  return found.sort();
}

/** Which file (repository-relative path) a relative import specifier points to; returns null if it cannot be resolved */
export function resolveSpec(root, fromRel, spec) {
  if (!spec.startsWith('.')) return null;
  const base = path.resolve(root, path.dirname(fromRel), spec);
  for (const e of ['', '.ts', '.tsx', '.mjs', '.js', '.d.mts', '/index.ts', '/index.tsx', '/index.mjs']) {
    try {
      if (statSync(base + e).isFile()) return path.relative(root, base + e).split(path.sep).join('/');
    } catch {
      /* Next */
    }
  }
  return null;
}

/*
 * 2026-10-28: Originally written as `[^;\n]*?`: excluding newlines, so **multiline forms were
 * completely invisible**:
 *   import {
 *     a,
 *   } from "../../cloud/x";
 * Single-line matches, multiline misses. As a result, both the G3 seam count and check #4 of the
 * sync script had false negatives, and "wrapping an offending import across multiple lines" is
 * precisely what happens most naturally during formatting. Changed to stop only at semicolons.
 */
const IMPORT_RE = /(?:^|\n)\s*(?:import|export)[^;]*?from\s*['"]([^'"]+)['"]|(?:await\s+)?import\s*\(\s*['"]([^'"]+)['"]\s*\)/g;

/** All relative targets imported by this file (repository-relative paths) */
export function importsOf(root, rel) {
  let src = '';
  try {
    src = readFileSync(path.join(root, rel), 'utf8');
  } catch {
    return [];
  }
  const hits = new Set();
  IMPORT_RE.lastIndex = 0;
  let m;
  while ((m = IMPORT_RE.exec(src))) {
    const target = resolveSpec(root, rel, m[1] || m[2]);
    if (target) hits.add(target);
  }
  return [...hits].sort();
}

/**
 * Find the spans occupied by **comments** in source code.
 *
 * Why this level of detail is needed: the gatekeeper rule is "never **load** `cloud/`", not
 * "never mention `cloud/`" (amendment in Section 2 of General Principles, 2026-10-27). Comments
 * like "the cloud counterpart of this logic is in `cloud/...`" are precisely the clues that should
 * remain after decoupling; they cannot fail. Therefore, comments must be extracted and excluded.
 *
 * Conversely, **`cloud/` inside a string is a violation**: concatenating strings into paths to
 * import is the easiest way to bypass the gatekeeper. Therefore, scanning must correctly skip
 * strings (so `//` in `'https://x'` is not treated as the start of a line comment) without
 * excluding strings themselves.
 */
export function commentRanges(src) {
  const ranges = [];
  let i = 0;
  const n = src.length;
  while (i < n) {
    const c = src[i];
    if (c === '/' && src[i + 1] === '/') {
      const start = i;
      while (i < n && src[i] !== '\n') i += 1;
      ranges.push([start, i]);
      continue;
    }
    if (c === '/' && src[i + 1] === '*') {
      const start = i;
      i += 2;
      while (i < n && !(src[i] === '*' && src[i + 1] === '/')) i += 1;
      i = Math.min(i + 2, n);
      ranges.push([start, i]);
      continue;
    }
    if (c === "'" || c === '"' || c === '`') {
      const quote = c;
      i += 1;
      while (i < n) {
        if (src[i] === '\\') { i += 2; continue; }
        if (src[i] === quote) { i += 1; break; }
        if (quote !== '`' && src[i] === '\n') break; // Unclosed single-line string; do not consume the entire file
        i += 1;
      }
      continue;
    }
    i += 1;
  }
  return ranges;
}

/** Is this position inside a comment */
export const inComment = (ranges, idx) => ranges.some(([a, b]) => idx >= a && idx < b);
