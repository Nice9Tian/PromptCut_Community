/**
 * Plan agent-workflow-plan.md A6: Agent custom measurement using JS (measure_audio_js).
 *
 * Cases CM-1-CM-14 (three tiers × this tool in creativity-gate.test.mjs CR-6 / CR-11):
 *   CM-1  Sample rate and window normalization (default 16 kHz, clamped to 8-48 kHz; start /
 *         duration slices window, errors out of bounds);
 *   CM-2  Sample count budget: if exceeded, do not decode first, error states clearly maximum
 *         seconds and how to reduce under this sample rate and channel count;
 *   CM-3  ffmpeg parameters: single file sliced by window, f32le output; timeline mix graph is
 *         identical to loudness measurement (timelineMeasureArgs);
 *   CM-4  Interleaved PCM channel splitting, discard incomplete trailing frames;
 *   CM-5  measureJs pre-checks (empty code, asset does not exist, no audio stream, invalid scope)
 *         do not decode, do not enter sandbox;
 *   ── Real ffmpeg and dedicated Chrome start below ──
 *   CM-6  Normal measurement: 1 kHz sine wave (amplitude 0.5) generated by ffmpeg lavfi, RMS and
 *         peak match theoretical values (-9.03 / -6.02 dBFS);
 *         Clip tier sliced by window, mono (mixed by average, loudness unchanged), timeline mix
 *         tier (volume 0.5 → 6.02 dB lower, same for mono);
 *   CM-7  Infinite loop terminated within time limit, editor process (this process) event loop runs
 *         as usual;
 *   CM-8  Memory bomb returns clear error (heartbeat determines freeze / allocation failure),
 *         returns within seconds, subsequent measurements proceed as usual;
 *   CM-9  Network attempt fails: fetch / XHR / WebSocket / importScripts throw "cannot access
 *         network in sandbox"; HTTP service on local loopback was never hit;
 *   CM-10 Throws exception with error text and line number; syntax error also returns clear message;
 *   CM-11 Oversized result rejected;
 *   CM-12 Non-serializable result (BigInt, circular reference, undefined) rejected;
 *   CM-13 Code cannot access Node capabilities (no process, require, Buffer), forged result via
 *         postMessage fails;
 *   CM-14 Time limit normalization, code length upper limit, queue upper limit.
 *
 * Run: node --test server/test/custom-measure.test.mjs (requires ffmpeg and chrome-headless-shell;
 * skips CM-6 onwards when ffmpeg is not found)
 */
