/**
 * Generate sounds first when export starts (`docs/semantics/product/rendering.md` "Audible motion graphics cards", user decision, 2026-10-06):
 * all sounds that are not generated, missing or stale are generated first, then the picture starts rendering; generation progress counts toward export progress; canceling export also cancels generation;
 * it fails only when a given sound truly cannot be generated, and says which clip. Desktop export and online browser export both go through here
 * (`exportVideo` in `src/editor/io/index.ts`, `exportVideoOnline` in `src/export/onlineExport.ts`).
 *
 * Two kinds of sound are handled:
 *   - Standalone sound effects (notification sounds, keyboard sounds): the clip stores a recipe (`clip.soundEffect`), and the sound is an ordinary WAV asset;
 *   - Audible motion graphics cards: the sound belongs to a visual clip (`clip.cardAudio`) and is generated by the card's `audio()`.
 * Audio media effect cards (nodes with `kind: 'audio'`) are not handled here: they have no persistent output and are synthesized on the spot when mixing for export.
 *
 * No half-finished output is left behind: each segment is "synthesize → store → one commit", and cancel or failure happens before the commit, leaving the project untouched;
 * segments fully generated before the cancel are kept (they are complete sounds, used directly by the next export).
 *
 * Online page: what this device cannot run (user cards, media effect cards) or what is judged heavy is not synthesized in the browser (`onlineSoundJudge.ts`);
 * if they have no output, export fails and names the clip.
 */
import type { Project, TrackClip } from "../../kernel/project";
import { audioProjectOf, findClipInCut } from "../../kernel/cutSegments";
import { CardAudioRenditionError, clipHasEmbeddedAudio } from "../../kernel/cardAudioRendition.mjs";
import { getCard, syncedUserCards } from "../../kernel/registry";
import { getState } from "../../store/project";
import { persistentCardAudio } from "../../audio/cardAudio";
import { hasGeneratedAudio } from "./generatedAudioUpload";
import { generateCardAudio } from "./cardAudioGeneration";
import { restoreSoundEffectAsset } from "./soundGeneration";
import { decideClipSound, requestSoundBackfill, type SoundDecision } from "./onlineSoundJudge";
import { tr } from "../../i18n/index.ts";

export type ExportSoundKind = "effect" | "card";
export type ExportSoundReason = "ungenerated" | "missing" | "stale";

export interface ExportSoundNeed {
  clipId: string;
  /**
   * Which cut the clip lives in; defaults to the active one. Audible clips in a cut referenced by a cut segment (`audioProjectOf` in `kernel/cutAudio.mjs`)
   * carry it, so generation is computed over that cut and the result is written back to that cut (`product/rendering.md` "Auto-generate sounds on export", recursing into cut segments).
   */
  cutId?: string;
  /** Clip name shown to the user */
  label: string;
  kind: ExportSoundKind;
  reason: ExportSoundReason;
  detail: string;
}

export interface ExportSoundsDeps {
  project: () => Project;
  /** Whether the current asset service has the complete bytes of this sound */
  hasBytes: (hash: string, signal: AbortSignal) => Promise<boolean>;
  generateCard: (clipId: string, options: { signal: AbortSignal; cutId?: string; onProgress: (done: number, total: number) => void }) => Promise<unknown>;
  restoreEffect: (clipId: string, options: { signal: AbortSignal; onProgress: (fraction: number) => void }) => Promise<unknown>;
  decide: (project: Project, clip: TrackClip, signal: AbortSignal) => Promise<SoundDecision>;
  backfill: (request: { project: Project; clip: TrackClip; reason: "heavy" | "not-runnable" }) => Promise<boolean>;
  embedded: (project: Project, clip: TrackClip) => boolean;
  resolveCard: (project: Project, clip: TrackClip) => { media: { hash?: string } };
}

const defaultDeps: ExportSoundsDeps = {
  project: () => getState().project,
  hasBytes: hasGeneratedAudio,
  generateCard: (clipId, options) => generateCardAudio(clipId, options),
  restoreEffect: (clipId, options) => restoreSoundEffectAsset(clipId, options),
  decide: decideClipSound,
  backfill: requestSoundBackfill,
  embedded: (project, clip) => clipHasEmbeddedAudio(project, clip, getCard) || !!syncedUserCards().get(clip.cardId)?.embeddedAudio,
  resolveCard: persistentCardAudio,
};

/** Export failure: which sound could not be generated */
export class ExportSoundError extends Error {
  readonly code = "export-sound-failed";
  readonly clipId: string;
  readonly label: string;
  constructor(need: Pick<ExportSoundNeed, "clipId" | "label">, reason: string) {
    super(tr("Cannot generate sound for clip \"{0}\" ({1}): {2}", need.label, need.clipId, reason));
    this.clipId = need.clipId;
    this.label = need.label;
  }
}

const cancelled = () => Object.assign(new Error(tr("Export canceled")), { cancelled: true });
const labelOf = (clip: TrackClip) => String(clip.label || getCard(clip.cardId)?.name || syncedUserCards().get(clip.cardId)?.name || clip.cardId || clip.id);

/**
 * Which sounds must be generated first for this export. The criteria match the mix plan (`src/kernel/audioPlan.mjs`): hidden and muted tracks and muted clips make no sound, so need no generation.
 * For those fully recorded in the project, the asset service is still asked once: bytes that are absent (asset service replaced, content store cleared) also count as missing.
 *
 * Cut segments: expanded the same way as the mix (`audioProjectOf`), walking into referenced cuts (any depth). Child clips are not sounded, so need no generation, when the cut segment is muted,
 * its track is muted or hidden, or they fall outside the segment's window; if the same cut is referenced several times, the clips inside are listed once (with `cutId`).
 */
export async function listExportSoundNeeds(signal: AbortSignal, overrides: Partial<ExportSoundsDeps> = {}): Promise<ExportSoundNeed[]> {
  const deps = { ...defaultDeps, ...overrides };
  const project = deps.project();
  const needs: ExportSoundNeed[] = [];
  const known = new Map<string, boolean>();
  const bytes = async (hash: string) => {
    if (!known.has(hash)) known.set(hash, await deps.hasBytes(hash, signal));
    return known.get(hash)!;
  };
  const seen = new Set<string>();
  const cutName = (cutId: string) => project.cuts?.find((c) => c.id === cutId)?.name ?? cutId;
  for (const track of audioProjectOf(project).tracks) {
    if (track.hidden || track.muted) continue;
    for (const derived of track.clips) {
      if (derived.audioMuted || !(derived.end > derived.start)) continue;
      if (signal.aborted) throw cancelled();
      // Expanded from a cut segment: swap back to its original clip in the referenced cut (identity and generation are both computed over that cut)
      const origin = derived.cutOrigin;
      const where = origin ? findClipInCut(project, origin.cutId, origin.clipId) : null;
      if (origin && !where) continue;
      const clip = where ? where.clip : derived, ctx = where ? where.view : project;
      const key = `${origin?.cutId ?? ""}/${clip.id}`;
      if (seen.has(key)) continue;
      seen.add(key);
      const at = origin ? { cutId: origin.cutId } : {};
      const label = origin ? tr("\"{1}\" in cut \"{0}\"", cutName(origin.cutId), labelOf(clip)) : labelOf(clip);
      if (clip.soundEffect && !clip.nodeId) {
        const media = project.media.find((m) => m.id === clip.mediaId);
        const base = { clipId: clip.id, ...at, label, kind: "effect" as const, reason: "missing" as const };
        if (!media || media.kind !== "audio" || !media.hash || !media.url || media.pending) needs.push({ ...base, detail: tr("The project has no media record for this sound effect") });
        else if (!(await bytes(media.hash))) needs.push({ ...base, detail: tr("The asset service has no file for this sound effect") });
        continue;
      }
      if (!deps.embedded(ctx, clip)) continue;
      const base = { clipId: clip.id, ...at, label, kind: "card" as const };
      try {
        const hash = deps.resolveCard(ctx, clip).media.hash;
        if (!hash || !(await bytes(hash))) needs.push({ ...base, reason: "missing", detail: tr("The asset service has no file for this card audio") });
      } catch (error) {
        const code = error instanceof CardAudioRenditionError ? error.code : "missing";
        const message = error instanceof Error ? error.message : String(error);
        needs.push({ ...base, reason: code === "stale" ? "stale" : clip.cardAudio ? "missing" : "ungenerated", detail: message });
      }
    }
  }
  return needs;
}

export interface PrepareExportSoundsOptions {
  signal: AbortSignal;
  /** `done` may be fractional (how far along the segment being generated is), `total` is the number of segments to generate */
  onProgress?: (done: number, total: number) => void;
  /** The manifest already built (when the caller lists first to decide whether to show this step, pass it in to avoid asking the asset service again) */
  needs?: ExportSoundNeed[];
  deps?: Partial<ExportSoundsDeps>;
}

/**
 * Generates the sounds in the manifest one segment at a time. Returns only if all succeed; on cancel it throws
 * `{ cancelled: true }`; if a segment cannot be generated it throws `ExportSoundError` (with the clip).
 */
export async function prepareExportSounds(options: PrepareExportSoundsOptions): Promise<{ total: number; generated: string[] }> {
  const deps = { ...defaultDeps, ...options.deps };
  const { signal } = options;
  const needs = options.needs ?? await listExportSoundNeeds(signal, deps);
  const total = needs.length;
  const generated: string[] = [];
  if (!total) return { total, generated };
  options.onProgress?.(0, total);
  for (let i = 0; i < total; i++) {
    const need = needs[i];
    if (signal.aborted) throw cancelled();
    const part = (fraction: number) => options.onProgress?.(i + Math.max(0, Math.min(0.99, fraction)), total);
    try {
      const hit = findClipInCut(deps.project(), need.cutId, need.clipId);
      if (!hit) throw new Error(tr("The clip is no longer in the project"));
      const decision = await deps.decide(hit.view, hit.clip, signal);
      if (!decision.synth) {
        // The render node regenerates by the clips in the active cut; ones handed over from a referenced cut
        // can't be recognized either, so say so directly
        const handed = need.cutId ? false : await deps.backfill({ project: hit.view, clip: hit.clip, reason: decision.reason });
        throw new Error(handed ? tr("{0} (handed to a render node for generation; export again once it is generated)", decision.message) : decision.message);
      }
      if (need.kind === "effect") {
        // Recovery of a standalone sound effect must commit by the clips of the active cut
        // (`actions.commitSoundEffect`): ones in a referenced cut can only be generated after switching to it
        if (need.cutId) throw new Error(tr("This sound effect is in a referenced cut; open that cut and regenerate it, then export"));
        await deps.restoreEffect(need.clipId, { signal, onProgress: part });
      } else await deps.generateCard(need.clipId, { signal, ...(need.cutId ? { cutId: need.cutId } : {}), onProgress: (done, all) => part(all ? done / all : 0) });
    } catch (error) {
      if (signal.aborted || (error as { cancelled?: boolean })?.cancelled || (error as Error)?.name === "AbortError") throw cancelled();
      throw new ExportSoundError(need, error instanceof Error ? error.message : String(error));
    }
    generated.push(need.clipId);
    options.onProgress?.(i + 1, total);
  }
  return { total, generated };
}
