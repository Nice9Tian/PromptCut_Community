/**
 * remotion-style framework: when a card is loaded, lock the objects at the top level of its file
 * wholesale into read-only.
 *
 * Why it exists: for a remotion-style card, the picture of a frame may only be computed from the time
 * t and the parameters. To carry something from the previous frame to the next, it would have to
 * write somewhere that lives longer than one frame, and variables at the top level of the card file
 * are the handiest such place. The card-creation check can spot direct writes (`COUNTER.n += 1`) but
 * not roundabout ones (`const c = COUNTER; c.n += 1`). So at load time all top-level objects are
 * frozen: whichever way a write comes in, it errors on the spot at the moment of writing. This is
 * done once when the module loads, not every frame.
 *
 * Who calls it: the two paths that load user cards append a call at the end of the card source
 * (generated by `../../online/cardRuntime/remotionLock.mjs`): on the desktop app and the render nodes
 * it is the dev server's transform hook, and on the online page it is the transpile step. It is only
 * appended after user cards that "declare themselves remotion-style and import this framework": a
 * card created before the framework existed cannot import it, so not a single old card gets locked.
 *
 * What is locked and what is not:
 *   - plain objects, arrays: frozen themselves, and the values inside are locked in turn;
 *   - functions: the function object itself is frozen (nothing may be attached to a function);
 *     regular expressions: frozen (`lastIndex` can no longer advance);
 *   - Map, Set: the methods that change content are replaced with ones that error as soon as they are
 *     called, then frozen;
 *   - things exported by other modules (React, the framework itself, built-in shared constants): not
 *     this card's, so untouched;
 *   - things carrying `$$typeof`, such as React elements: untouched (React dev mode itself needs to
 *     record things in them);
 *   - things that cannot be locked (fixed-length array buffers, DOM nodes, class instances,
 *     Promises, ...): error directly at load time, saying which one it is.
 */

/**
 * A top-level name and the function that fetches its value (a function is used because the name may
 * be just a type; if it cannot be fetched, skip it)
 */
export type TopLevelEntry = readonly [name: string, get: () => unknown];

const isObjectLike = (v: unknown): v is object => (typeof v === "object" && v !== null) || typeof v === "function";

const isPlain = (v: object): boolean => {
  const proto = Object.getPrototypeOf(v);
  return proto === Object.prototype || proto === null;
};

/**
 * Exports of other modules, together with the level just below them: these are not this card's
 * objects, so they are neither frozen nor descended into
 */
function foreignSet(foreign: readonly unknown[]): WeakSet<object> {
  const set = new WeakSet<object>();
  const addChildren = (v: object) => {
    let values: unknown[];
    try { values = Array.isArray(v) ? [...v] : Object.values(v); } catch { return; }
    for (const child of values) if (isObjectLike(child)) set.add(child);
  };
  for (const ns of foreign) {
    if (!isObjectLike(ns)) continue;
    set.add(ns);
    let names: (string | symbol)[];
    try { names = Reflect.ownKeys(ns); } catch { continue; }
    for (const name of names) {
      let value: unknown;
      try { value = (ns as Record<string | symbol, unknown>)[name]; } catch { continue; } // An export not yet initialized in a circular import
      if (!isObjectLike(value)) continue;
      set.add(value);
      if (typeof value === "object" && (Array.isArray(value) || isPlain(value))) addChildren(value);
    }
  }
  return set;
}

const typeName = (v: object): string => {
  const tag = Object.prototype.toString.call(v).slice(8, -1);
  const ctor = (v as { constructor?: { name?: unknown } }).constructor?.name;
  return tag === "Object" && typeof ctor === "string" && ctor && ctor !== "Object" ? ctor : tag;
};

function refuse(file: string, path: string, what: string): never {
  throw new TypeError(`remotion-style card ${file}: ${what}. Top-level ${path} is locked read-only: a frame must be computed only from time t and parameters, and cannot store anything for the next frame.`);
}

const MAP_MUTATORS = ["set", "delete", "clear"] as const;
const SET_MUTATORS = ["add", "delete", "clear"] as const;

function lockCollection(target: object, methods: readonly string[], file: string, path: string): void {
  for (const m of methods) {
    Object.defineProperty(target, m, {
      value: () => refuse(file, path, `writing to top-level ${path} (${m})`),
      writable: false, enumerable: false, configurable: false,
    });
  }
}

function deepLock(value: unknown, path: string, file: string, foreign: WeakSet<object>, seen: WeakSet<object>, depth: number): void {
  if (!isObjectLike(value) || foreign.has(value) || seen.has(value)) return;
  seen.add(value);
  if (depth > 64) return;
  if (typeof value === "function") { Object.freeze(value); return; }
  if ("$$typeof" in value) return;
  if (Array.isArray(value)) {
    for (let i = 0; i < value.length; i++) deepLock(value[i], `${path}[${i}]`, file, foreign, seen, depth + 1);
    Object.freeze(value);
    return;
  }
  if (value instanceof Map) {
    for (const [k, v] of value) { deepLock(k, `key of ${path}`, file, foreign, seen, depth + 1); deepLock(v, `value of ${path}`, file, foreign, seen, depth + 1); }
    lockCollection(value, MAP_MUTATORS, file, path);
    Object.freeze(value);
    return;
  }
  if (value instanceof Set) {
    for (const v of value) deepLock(v, `member of ${path}`, file, foreign, seen, depth + 1);
    lockCollection(value, SET_MUTATORS, file, path);
    Object.freeze(value);
    return;
  }
  if (value instanceof RegExp) { Object.freeze(value); return; }
  if (isPlain(value)) {
    for (const key of Reflect.ownKeys(value)) {
      const d = Object.getOwnPropertyDescriptor(value, key);
      if (d && "value" in d) deepLock(d.value, `${path}.${String(key)}`, file, foreign, seen, depth + 1);
    }
    Object.freeze(value);
    return;
  }
  throw new TypeError(`remotion-style card ${file}: top-level ${path} is ${typeName(value)} and cannot be locked read-only. Only numbers, strings, plain objects, arrays and functions belong at the top level of a card file; compute anything else inside a function.`);
}

/**
 * Lock the things at the top level of a card file into read-only. Called once at load time.
 * @param file     the card file (used in error messages)
 * @param entries  each top-level name and its value-fetching function
 * @param foreign  the modules this card imports (their exports are not this card's, so not locked)
 */
export function lockTopLevel(file: string, entries: readonly TopLevelEntry[], foreign: readonly unknown[] = []): void {
  const skip = foreignSet(foreign);
  const seen = new WeakSet<object>();
  for (const [name, get] of entries) {
    let value: unknown;
    try { value = get(); } catch { continue; } // Names that are only types, or not yet initialized: there is no value to lock
    deepLock(value, name, file, skip, seen, 0);
  }
}
