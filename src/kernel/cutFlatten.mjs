/**
 * "Flattened view" of cut segments: the project used for the planning side (cost identity,
 * measurement, dispatch, track stream planning, layer table, input signature, ready index), where
 * cut segments are replaced with their inner clips (`mechanism/rendering.md` "Cut segments";
 * (user decision, 2026-10-21): cards in cut segments behave the same as without cut segments, with
 * light cards live rendered and heavy cards each taking track streams).
 *
 * Visuals go through nested scenes as before (`render/CutSegmentScene.tsx`); no visual output here.
 * The flattened view only answers "what cards exist right now, which span of the parent timeline
 * each occupies, and what content each holds", letting dispatch, measurement, and stream generation
 * treat cards in referenced cuts as regular cards on the parent timeline.
 *
 *   - Each cut segment in the active cut (whose track is not hidden, not dangling, not cyclical) is
 *     replaced with clips from the referenced cut, recursing to arbitrary depth; visual track
 *     position is the track where the segment resides (painter's order unchanged). The segment
 *     itself is not in the flattened view;
 *   - Virtual clip id = `<segment id>~<inner clip id>` (chained through multiple layers, `FLAT_SEP`),
 *     and virtual track id is similar;
 *   - Time: parent time = referenced cut time + `segment.start − segment.cutOffset`; only the exposed
 *     window is kept: intersection of `[segment.start, segment.end)`, `total duration of referenced cut`,
 *     and the clip's own interval;
 *   - Boxes, parameters, and parts follow the inner clip as is. The referenced cut and project share
 *     the same aspect ratio; single-card streams are produced in the wrapper layer's own coordinate
 *     system, and segment boxes (position, scale, rotation, opacity, fade) do not enter stream
 *     pixels, but are applied by outer wrapper layers around nested scenes during pasting: same
 *     principle as top-level card scale and rotation not entering the stream;
 *   - Also carries `flat`: `lead` is the local time of this card at the moment the exposed start begins
 *     (> 0 when clip head is trimmed by the segment), `chain` is the traversed cut segments
 *     (`{ id, cutId, start, end, cutOffset }`), `mount` is the safe playback start when producing
 *     streams (seconds, `max(0, start − cutOffset)` of the top segment: nested scene mounts from here
 *     at the earliest, preroll will not precede it). `flat` enters this card's prerender key
 *     (`withFlatNodes`), but not the cost key.
 *
 * v1 only flattens card clips (`cardId`, without `nodeId`) and media clips. Clips with attached
 * media effect card nodes (`nodeId`) and transitions are not flattened: node inputs reference
 * original clip ids and would dangle if ids changed; they live render in nested scenes as before
 * and do not enter the dispatch table.
 *
 * Projects without cut segments return the same object as is; keys, tables, and signatures remain
 * unchanged byte-for-byte. Pure JS, shared between pages and server, does not touch registries (does
 * not use frame-push conventions).
 */

/** Delimiter for virtual clip ids. Clip ids are generated by `newId` (letters, digits, `-`), so it never appears */
export const FLAT_SEP = '~';

import { clipSpeed } from "./clipTime.mjs";

const FALLBACK_CUT_DURATION = 30;
const MAX_DEPTH = 32;
const EPS = 1e-9;

/** Whether this clip id is a flattened virtual clip */
export const isFlatClipId = (id) => typeof id === 'string' && id.includes(FLAT_SEP);

const isSegment = (c) => !!c && typeof c.cutId === 'string' && c.cutId.length > 0;

function activeIdOf(p) {
  const cuts = Array.isArray(p?.cuts) ? p.cuts : [];
  if (!cuts.length) return undefined;
  return p.activeCutId && cuts.some((c) => c.id === p.activeCutId) ? p.activeCutId : cuts[0].id;
}

/** Cut content (same as `cutContent` in `cutSegments.ts`); returns null if not found */
function contentOf(p, cutId) {
  const cuts = Array.isArray(p?.cuts) ? p.cuts : [];
  const entry = cuts.find((c) => c?.id === cutId);
  if (!entry) return null;
  const kind = entry?.kind === '3d' ? '3d' : '2d';
  if (cutId === activeIdOf(p)) return { tracks: p.tracks ?? [], duration: Number(p.duration) || 0, kind };
  if (!Array.isArray(entry.tracks)) return null;
  return { tracks: entry.tracks, duration: typeof entry.duration === 'number' && entry.duration > 0 ? entry.duration : FALLBACK_CUT_DURATION, kind };
}

/** Whether the project's active cut has cut segments to flatten */
export function hasFlatSegments(project) {
  for (const track of project?.tracks ?? []) {
    if (track?.hidden) continue;
    for (const c of track?.clips ?? []) if (isSegment(c)) return true;
  }
  return false;
}

function expandSegment(project, seg, ctx, out, trackIdPrefix) {
  const cutId = seg.cutId;
  if (ctx.path.includes(cutId) || ctx.path.length >= MAX_DEPTH) return;
  const content = contentOf(project, cutId);
  if (!content) return;
  const start = Number(seg.start), end = Number(seg.end);
  if (!Number.isFinite(start) || !Number.isFinite(end) || !(end > start)) return;
  const segStart = ctx.shift + start, segEnd = ctx.shift + end;
  const offset = Math.max(0, Number(seg.cutOffset) || 0);
  const shift = segStart - offset;
  const from = Math.max(ctx.from, segStart);
  const to = Math.min(ctx.to, segEnd, shift + content.duration);
  if (!(to > from + EPS)) return;
  const chain = [...ctx.chain, { id: seg.id, cutId, start, end, cutOffset: offset }];
  const mount = ctx.mount ?? Math.max(0, segStart - offset);
  const idPrefix = `${ctx.idPrefix}${seg.id}${FLAT_SEP}`;
  const in3dCut = Boolean(ctx.in3dCut || content.kind === '3d');
  const inner = { shift, from, to, chain, mount, idPrefix, in3dCut, path: [...ctx.path, cutId] };
  for (const track of content.tracks) {
    if (!track || track.hidden || track.sourceOnly) continue;
    const trackId = `${trackIdPrefix}${FLAT_SEP}${seg.id}${FLAT_SEP}${track.id}`;
    const clips = [];
    for (const c of track.clips ?? []) {
      if (!c || typeof c.id !== 'string') continue;
      if (isSegment(c)) { expandSegment(project, c, inner, out, trackId); continue; }
      if (c.nodeId) continue;
      if (!c.cardId && !c.mediaId) continue;
      const s = Number(c.start) + shift, e = Number(c.end) + shift;
      if (!Number.isFinite(s) || !Number.isFinite(e)) continue;
      const vs = Math.max(from, s), ve = Math.min(to, e);
      if (!(ve > vs + EPS)) continue;
      const lead = vs - s;
      const v = { ...c, id: `${idPrefix}${c.id}`, start: vs, end: ve, flat: { lead, chain, mount, ...(in3dCut ? { in3dCut: true } : null) } };
      // Advance asset start per clip speed for trimmed portion (kernel/clipTime.mjs; when default 1, lead × 1 = lead, bitwise unchanged)
      if (c.mediaId && lead > 0) v.mediaOffset = (Number(c.mediaOffset) || 0) + lead * clipSpeed(c);
      clips.push(v);
    }
    if (clips.length) out.push({ ...track, id: trackId, clips });
  }
}

const memo = new WeakMap();

/**
 * Flattened view (see file header). Returns the same object when there are no cut segments;
 * memoized for the same project object (the page queries every tick).
 * There are no cut segments in the flattened view; flattening again still returns itself.
 */
export function flatPlanProject(project) {
  if (!project || !Array.isArray(project.tracks) || !hasFlatSegments(project)) return project;
  const hit = memo.get(project);
  if (hit) return hit;
  const root = activeIdOf(project);
  const tracks = [];
  for (const track of project.tracks) {
    if (!track || track.hidden || !(track.clips ?? []).some(isSegment)) { tracks.push(track); continue; }
    for (const seg of track.clips) {
      if (!isSegment(seg)) continue;
      expandSegment(project, seg, { shift: 0, from: -Infinity, to: Infinity, chain: [], mount: undefined, idPrefix: '', path: root ? [root] : [] }, tracks, track.id);
    }
    tracks.push({ ...track, clips: track.clips.filter((c) => !isSegment(c)) });
  }
  const out = { ...project, tracks };
  memo.set(project, out);
  return out;
}

/** Flattening information carried by the clip (returns undefined for top-level clips) */
export function flatInfoOf(clip) {
  const f = clip?.flat;
  return f && typeof f === 'object' && Array.isArray(f.chain) ? f : undefined;
}

/** Find clip and its track by id in the flattened view */
export function flatClipOf(project, clipId) {
  const flat = flatPlanProject(project);
  for (const track of flat?.tracks ?? []) for (const clip of track?.clips ?? []) if (clip?.id === clipId) return { track, clip };
  return null;
}

/**
 * Fills in `flat` (`lead`, `chain`, `mount`) on base nodes of virtual clips in the card plan graph
 * (result of `projectCardGraph(flatPlanProject(p))`): how much head was trimmed by the exposed
 * window and which cut segment layers were traversed all modify this card's pixels in the stream,
 * so they enter its content key and stream member key; stripped from the cost key (`cardCostKey`).
 * Base nodes are `@clip/<id>/source` (regular cards, media clips) or `@clip/<id>/card` (media effect
 * card syntax with only `cardId`); filter and emphasis layers carry it along through input keys.
 * Returns the same graph as is when there are no virtual clips.
 */
export function withFlatNodes(flatProject, graph) {
  if (!graph || !Array.isArray(graph?.nodes)) return graph;
  const info = new Map();
  for (const track of flatProject?.tracks ?? []) for (const clip of track?.clips ?? []) {
    const f = flatInfoOf(clip);
    if (!f) continue;
    const flat = { lead: f.lead, chain: f.chain, mount: f.mount };
    info.set(`@clip/${clip.id}/source`, flat);
    info.set(`@clip/${clip.id}/card`, flat);
  }
  if (!info.size) return graph;
  let changed = false;
  const nodes = graph.nodes.map((node) => {
    const flat = info.get(node?.id);
    if (!flat) return node;
    changed = true;
    return { ...node, flat };
  });
  return changed ? { ...graph, nodes } : graph;
}

/** Strip the cut segment's own appearance: box (nested scene fills frame 1:1), opacity, fade, emphasis, motion path */
function bareSegment(seg) {
  const out = structuredClone(seg);
  delete out.frame; delete out.frameExpr; delete out.opacity; delete out.fadeIn; delete out.fadeOut; delete out.emphasis; delete out.motion;
  return out;
}

/** Keep only this single clip `keepId` visible in a group of tracks (same as `isolatedStreamProject` in `server/frame-stream.mjs`): other tracks and other clips in the same track are hidden as `sourceOnly` */
function isolateTracks(tracks, keepId, transform) {
  const ids = new Set((tracks ?? []).map((t) => t.id));
  const out = [];
  for (const track of tracks ?? []) {
    const own = (track.clips ?? []).filter((c) => c.id === keepId);
    if (!own.length) { out.push({ ...structuredClone(track), hidden: true, sourceOnly: true }); continue; }
    out.push({ ...structuredClone(track), hidden: false, sourceOnly: false, clips: own.map(transform) });
    const siblings = (track.clips ?? []).filter((c) => c.id !== keepId);
    if (siblings.length) {
      let id = `__pc_source_${track.id}`, n = 1;
      while (ids.has(id)) id = `__pc_source_${track.id}_${n++}`;
      ids.add(id);
      out.push({ ...structuredClone(track), id, hidden: true, sourceOnly: true, clips: structuredClone(siblings) });
    }
  }
  return out;
}

/**
 * **Isolated project** for the single-card stream of virtual clip `clipId`: starting from the real
 * project, only cut segments along this chain are kept (stripping segment appearance, nested scene
 * fills frame 1:1), and each referenced cut only retains the next segment on the chain or the target
 * card; target card is passed to `localize` (`localClip` in `server/frame-stream.mjs`: box placed at
 * snapshot position, appearance stripped). Nested scenes calculate preroll and trim heads as usual,
 * so each frame in the stream matches how this card looks inside the wrapper layer during live
 * render. Time is not shifted. Returns null if this clip is not found.
 */
export function isolatedFlatProject(project, clipId, localize = (c) => structuredClone(c)) {
  const hit = flatClipOf(project, clipId);
  const f = flatInfoOf(hit?.clip);
  if (!f || !f.chain.length) return null;
  const prefix = f.chain.map((s) => s.id).join(FLAT_SEP) + FLAT_SEP;
  if (!clipId.startsWith(prefix)) return null;
  const innerId = clipId.slice(prefix.length);
  const root = structuredClone(project);
  root.tracks = isolateTracks(root.tracks, f.chain[0].id, bareSegment);
  const rootActiveId = activeIdOf(root);
  if (rootActiveId && Array.isArray(root.cuts)) {
    const activeCut = root.cuts.find((c) => c?.id === rootActiveId);
    if (activeCut) { delete activeCut.kind; delete activeCut.cameras; }
  }
  for (let i = 0; i < f.chain.length; i++) {
    const entry = (root.cuts ?? []).find((c) => c?.id === f.chain[i].cutId);
    if (!entry || !Array.isArray(entry.tracks)) return null;
    delete entry.kind;
    delete entry.cameras;
    const last = i === f.chain.length - 1;
    entry.tracks = isolateTracks(entry.tracks, last ? innerId : f.chain[i + 1].id, last ? localize : bareSegment);
  }
  return { ...root, _cardRender: { mode: 'final', frames: {}, missing: {} } };
}
