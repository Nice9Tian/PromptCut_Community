/**
 * **Original isolation policy text** for online execution of user cards and media effect cards
 * (contract `docs/plan/online-card-exec-contract.md` sections 3.3 and 4.1).
 *
 * The policy text is written only in this one file and fetched here across four places, not copied
 * separately:
 *   - `<meta http-equiv="Content-Security-Policy">` injected by the online build into stage entry
 *     `stage.html` (`vite.config.ts`);
 *   - Local nginx-mimicking proxy (`scripts/probes/lib/hosted-proxy.mjs`, used together by probes
 *     and local isolated hosting);
 *   - Policy snippets in nginx templates (`server/hosted/deploy/nginx-snippet-*.conf`, generated by
 *     `cloud/scripts/gen-stage-policy-nginx.mjs`, unit test `stagePolicy.test.mjs` verifies
 *     templates match here);
 *   - Stage self-check (`isolation/isolationCheck.ts`) used to distinguish whether the policy comes
 *     from response headers or only `<meta>` fallback.
 *
 * Pure functions, no dependencies: directly importable by browsers, Node unit tests, and build
 * scripts.
 */

/** Name of the cookie exchanged from an asset ticket (HttpOnly, unreadable by card code) */
export const MEDIA_COOKIE = "pc_rt";
/** Cookie lifetime (seconds), same as validity period of read-only asset tickets (15 minutes) */
export const MEDIA_COOKIE_MAX_AGE_S = 900;
/** Path prefix for reading assets via cookie on stage origins: `/media-s/<sid>/media/<hash>`; ticket handover address is `/media-s/<sid>/_grant` */
export const MEDIA_S_PREFIX = "/media-s";
/** Shape of stage asset path id: fixed by account and project, kept secret from stages of other projects, scoping cookies and caches to a single path */
export const SID_PATTERN = "[A-Za-z0-9]{16,64}";
/** Paths permitted after `/media-s/<sid>/` (read-only asset bytes: both original size and small size are addressed by hash) */
export const MEDIA_S_PATH_PATTERN = "media/[0-9a-f]{64}(?:\\.[A-Za-z0-9]{1,8})?";
/**
 * Asset service's own API base URL (`server/asset-service.ts`: `<origin>/api/asset`, fixed by
 * contract). Appended after it when forwarding `/media-s/<sid>/media/<hash>` to the asset service;
 * the asset base URL on the editor page side must be `MEDIA_PROXY_BASE` reverse-proxied by `/media`
 * from the same asset service, otherwise it does not take this cookie path.
 */
export const ASSET_API_PREFIX = "/api/asset";
/** Base URL path of the asset service on the editor page origin (nginx `/media` reverse proxy + asset service API base URL) */
export const MEDIA_PROXY_BASE = "/media/api/asset";
/**
 * Shapes of asset tickets, two kinds, each hardcoded:
 * - Old shared projects (`server/auth/tickets.mjs`): `v1.<base64url>.<base64url>`, total length not
 *   exceeding 2048;
 * - Account cloud projects (`issue` in `cloud/docservice/account-hosted.mjs`: base64url of 32 random
 *   bytes): exactly 43 characters.
 * The nginx stage site template (`server/hosted/deploy/nginx-site-promptcut-stages.conf`) manually
 * writes the same regex; changes here must be updated together (tests will verify).
 */
export const TICKET_PATTERN = "(?:v1\\.[A-Za-z0-9_-]{1,1600}\\.[A-Za-z0-9_-]{1,200}|[A-Za-z0-9_-]{43})";

/**
 * Directives of the stage policy (fixed order, generated text is verbatim stable). `frame-ancestors`
 * can only appear in response headers (invalid in `<meta>`), listed separately.
 *
 * - `'unsafe-eval'`: Required to execute transpiled code (`new Function`); stage is already treated
 *   as untrusted, not relying on it to prevent injection.
 * - `worker-src blob:` without `'self'`: Workers started from same-origin script URLs do not inherit
 *   document policy, allowed only from blob URLs (inheriting creator's policy).
 * - External images, fonts, styles, scripts, and connections are allowed as usual; all three
 *   editions do not set card egress guards.
 * - frame/object/base/form constraints protect stage documents and embedding structures, without
 *   placing the editor page or accounts into the card's origin.
 */
const STAGE_DIRECTIVES = Object.freeze([
  "default-src 'none'",
  "script-src 'self' http: https: 'unsafe-eval'",
  "style-src 'self' http: https: 'unsafe-inline'",
  "img-src 'self' http: https: data: blob:",
  "media-src 'self' http: https: data: blob:",
  "font-src 'self' http: https: data:",
  "connect-src 'self' http: https: ws: wss:",
  "worker-src blob:",
  "frame-src 'none'",
  "object-src 'none'",
  "base-uri 'none'",
  "form-action 'none'",
]);

/** The section shared by response headers and `<meta>` */
const STAGE_CSP_BASE = STAGE_DIRECTIVES.join("; ");

/** Policy used by `<meta>` in stage entry `stage.html`: the shared section (excluding `frame-ancestors`, which is invalid in `<meta>`) */
export const STAGE_CSP_META = STAGE_CSP_BASE;

/** Directive names appearing only in the response header copy: stage self-check uses this to distinguish "policy comes from response headers" or "only `<meta>` fallback" */
export const STAGE_CSP_HEADER_ONLY_DIRECTIVE = "frame-ancestors";

/** An origin: `http(s)://host[:port]`, without path */
function checkOrigin(origin, what) {
  let u;
  try { u = new URL(String(origin)); } catch { throw new Error(`${what} is not a valid origin: ${String(origin)}`); }
  if ((u.protocol !== "https:" && u.protocol !== "http:") || u.origin !== String(origin)) throw new Error(`${what} is not a valid origin: ${String(origin)}`);
  return u.origin;
}

/**
 * Response header policy for stage origins: carried by stage documents and all script and asset
 * responses on the stage origin. `editorOrigin` is the origin of the editor page (only it can embed
 * the stage in an iframe).
 * In nginx templates, `editorOrigin` is `https://{{DOMAIN}}` (placeholders are passed in as is
 * without validation).
 */
export function stageCspHeader(editorOrigin, { template = false } = {}) {
  const origin = template ? String(editorOrigin) : checkOrigin(editorOrigin, "editor page origin");
  return `${STAGE_CSP_BASE}; ${STAGE_CSP_HEADER_ONLY_DIRECTIVE} ${origin}`;
}

/**
 * Iframe origin used by third-party login (Google Identity Services) to render buttons and popups.
 * (production test, 2026-10-23): if not allowed, "Continue with Google" on the login page will be
 * blocked by this CSP (console reports `Framing 'https://accounts.google.com/' violates ... frame-src`),
 * even if the origin is configured on the console side, it still does not help.
 */
export const THIRD_PARTY_SIGNIN_FRAME_ORIGIN = "https://accounts.google.com";

/**
 * Policy for the editor page: only adds the single rule required for stage isolation: stage
 * iframes can load only this origin, the two stage origins, plus the third-party login origin (see
 * above). Navigating away by itself is also governed by this rule.
 * `blob:` and `data:` are not permitted: the editor page itself has no such subframes.
 */
export function editorCspHeader(stageOrigins, { template = false } = {}) {
  const list = (Array.isArray(stageOrigins) ? stageOrigins : []).map((o) => (template ? String(o) : checkOrigin(o, "stage origin")));
  return ["frame-src 'self'", ...list, THIRD_PARTY_SIGNIN_FRAME_ORIGIN].join(" ");
}

/**
 * Security headers included on **every** response on stage origins (lowercase name → value).
 * `Origin-Agent-Cluster`, `Referrer-Policy`, and `X-Content-Type-Options` are original and kept as
 * is; Document Policy and disabling DNS prefetch are retained, and no egress whitelist is set for
 * external resources.
 */
export function stageSecurityHeaders(editorOrigin, opts = {}) {
  return {
    "content-security-policy": stageCspHeader(editorOrigin, opts),
    "x-dns-prefetch-control": "off",
    "origin-agent-cluster": "?1",
    "referrer-policy": "no-referrer",
    "x-content-type-options": "nosniff",
  };
}

/** Additional headers included on editor page responses */
export function editorSecurityHeaders(stageOrigins, opts = {}) {
  return { "content-security-policy": editorCspHeader(stageOrigins, opts) };
}

/* ------------------------------------------------------------------ Exchange ticket for cookie (contract section 4.1) */

const SID_RE = new RegExp(`^${SID_PATTERN}$`);
const TICKET_RE = new RegExp(`^${TICKET_PATTERN}$`);
const MEDIA_S_RE = new RegExp(`^${MEDIA_S_PREFIX}/(${SID_PATTERN})/(.*)$`);
const MEDIA_S_PATH_RE = new RegExp(`^${MEDIA_S_PATH_PATTERN}$`);

export function isSid(v) { return typeof v === "string" && SID_RE.test(v); }
export function isTicketShaped(v) { return typeof v === "string" && v.length <= 2048 && TICKET_RE.test(v); }

/** Address for ticket handover (editor page sends one POST with credentials to each stage origin) */
export function mediaGrantUrl(stageOrigin, sid) {
  return `${stageOrigin}${MEDIA_S_PREFIX}/${sid}/_grant`;
}
/** Base URL for stage fetching assets (relative to stage's own origin; followed by `/media/<hash>`) */
export function mediaSBase(sid) {
  return `${MEDIA_S_PREFIX}/${sid}`;
}

/** `Set-Cookie` value. `secure`: always true for https sites; false when local proxy uses http (used when local http origin cannot set cookies with Secure) */
export function mediaGrantCookie(sid, ticket, { secure = true } = {}) {
  return `${MEDIA_COOKIE}=${ticket}; Path=${MEDIA_S_PREFIX}/${sid}/; HttpOnly; ${secure ? "Secure; " : ""}SameSite=Strict; Max-Age=${MEDIA_COOKIE_MAX_AGE_S}`;
}

/** Cross-origin response headers for handover requests (only open to editor page origin; carries credentials, so cannot be `*`) */
export function mediaGrantCorsHeaders(editorOrigin) {
  return {
    "access-control-allow-origin": editorOrigin,
    "access-control-allow-credentials": "true",
    "access-control-allow-headers": "authorization",
    "access-control-allow-methods": "POST",
    "access-control-max-age": "600",
    vary: "Origin",
  };
}

/**
 * What to do with an incoming request on `/media-s/…` (same determination for nginx template and
 * local proxy; pure function, verified item by item in unit tests):
 *
 *   { kind: "none" }                       Not this route
 *   { kind: "reject", status }             Reject (404 invalid path, 405 invalid method, 403 invalid origin, 400 invalid ticket format, 401 missing cookie)
 *   { kind: "preflight", headers }         Handover preflight: 204
 *   { kind: "grant", headers }             Handover: 204, with `Set-Cookie`
 *   { kind: "proxy", path, authorization } Read asset: forward to asset service `path` (`/api/asset/media/<hash>`), replace `Authorization` with ticket from cookie (do not forward cookie)
 */
export function mediaSRoute({ method, pathname, origin, authorization, cookie }, { editorOrigin, secure = true }) {
  const m = MEDIA_S_RE.exec(String(pathname || ""));
  if (!m) return String(pathname || "").startsWith(`${MEDIA_S_PREFIX}/`) ? { kind: "reject", status: 404 } : { kind: "none" };
  const sid = m[1], rest = m[2];
  const verb = String(method || "GET").toUpperCase();
  if (rest === "_grant") {
    if (verb === "OPTIONS") return origin === editorOrigin ? { kind: "preflight", headers: mediaGrantCorsHeaders(editorOrigin) } : { kind: "reject", status: 403 };
    if (verb !== "POST") return { kind: "reject", status: 405 };
    if (origin !== editorOrigin) return { kind: "reject", status: 403 };
    const t = /^Bearer[ \t]+(\S+)$/i.exec(String(authorization || "").trim())?.[1];
    if (!isTicketShaped(t)) return { kind: "reject", status: 400 };
    return { kind: "grant", headers: { ...mediaGrantCorsHeaders(editorOrigin), "set-cookie": mediaGrantCookie(sid, t, { secure }), "cache-control": "no-store" } };
  }
  if (!MEDIA_S_PATH_RE.test(rest)) return { kind: "reject", status: 404 };
  if (verb !== "GET" && verb !== "HEAD") return { kind: "reject", status: 405 };
  const ticket = cookieValue(cookie, MEDIA_COOKIE);
  if (!isTicketShaped(ticket)) return { kind: "reject", status: 401 };
  return { kind: "proxy", path: `${ASSET_API_PREFIX}/${rest}`, authorization: `Bearer ${ticket}` };
}

/** Extract a value from `Cookie` header; return null if absent */
export function cookieValue(header, name) {
  for (const part of String(header || "").split(/;\s*/)) {
    const i = part.indexOf("=");
    if (i > 0 && part.slice(0, i).trim() === name) return part.slice(i + 1).trim();
  }
  return null;
}
