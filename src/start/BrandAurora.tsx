/**
 * The base of the left block of the login page: flowing aurora + striped frosted glass + noise grain (direction set by the user, 2026-10-23).
 *
 * Three layers are stacked, all within the bounds of this block, with no effect at all on the form side on the right:
 *   1. **Aurora**: three large color blobs, drawn as radial gradients in the brand colors
 *      (`--ui-accent` cyan, `--ui-accent-2` purple) and then heavily blurred;
 *      each of the three runs on its own period (durations that do not divide each other), so it
 *      always seems to be changing and never falls into a beat;
 *   2. **Striped frosted glass**: a layer over the aurora; `backdrop-filter` blurs the aurora behind
 *      it, then a stripe mask frosts only a series of diagonal bars, and between the stripes it is
 *      clear, so the aurora is cut into alternating light and dark bands;
 *   3. **Noise**: grain generated by `feTurbulence`, laid on top at very low opacity to remove the
 *      plastic look of the large color blocks.
 *
 * **Why not a prerendered GIF** (the user mentioned Three + ray tracing rendered into a looping GIF):
 *   - A GIF has only 256 colors and the aurora is all smooth gradients, so banding is certain; hiding
 *     it needs dithering, and the file gets bigger;
 *   - This is the first screen of the online editor; a full-bleed animated image is several MB and
 *     slows the first open;
 *   - Most important, **the colors must follow the skin**: the brand color is set by `--ui-accent`,
 *     and when the user changes skin or accent color it has to change with them
 *     (`src/skins/`); a prerendered image is baked in and no longer matches after a skin change.
 *   This CSS approach is vector, follows variables, downloads nothing extra, and moves the way it is described.
 *   If we truly want an effect only offline rendering can do (volumetric light, real refraction),
 *   we can make a separate static base image and put it under the aurora,
 *   and discuss it then; it is not worth sacrificing skin switching and the first screen for it now.
 *
 * All parameters are in CSS custom properties (`.ps-aurora` in `start.css`); change the numbers to change the pattern.
 * People who turn off animation (`prefers-reduced-motion`) see only a still frame, with the same composition.
 */
import { useId } from "react";
import type { JSX } from "react";

export function BrandAurora(): JSX.Element {
  // The id of the noise filter: a page may have several instances, so it must not collide (Logo.tsx does the same)
  const uid = useId().replace(/:/g, "");
  return (
    <div className="ps-aurora" aria-hidden="true">
      <span className="ps-aurora-blob is-a" />
      <span className="ps-aurora-blob is-b" />
      <span className="ps-aurora-blob is-c" />
      {/* Striped frosted glass: backdrop-filter blurs the aurora behind, the stripe mask frosts only the diagonal bars */}
      <span className="ps-aurora-glass" />
      {/* Noise: the grain itself is generated by the filter, no image is downloaded */}
      <svg className="ps-aurora-grain">
        <filter id={`pc-grain-${uid}`}>
          <feTurbulence type="fractalNoise" baseFrequency="0.82" numOctaves="3" stitchTiles="stitch" />
          <feColorMatrix type="saturate" values="0" />
        </filter>
        <rect width="100%" height="100%" filter={`url(#pc-grain-${uid})`} />
      </svg>
    </div>
  );
}
