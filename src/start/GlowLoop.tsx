/**
 * The **finished product** of the home page's background glow: a looping video prerendered by
 * PromptCut's own renderer.
 *
 * User decision, 2026-10-24: "Change all three places to loop videos prerendered by the renderer:
 * desktop login page, mobile login, website home page."
 * The aurora in the left rail of the desktop login page is `BrandLoop`; this one handles the
 * background of the mobile login (the website home page doesn't go through React: it is a static
 * page under `site/` in the VisuHive repo, and uses the wide version made by the same renderer).
 *
 * The videos are batch-produced by `scripts/login-art/render-glow.mjs`, sourced from the same GLSL
 * in `BrandGlow.tsx` (via the user card `pc-brand-glow` generated by
 * `scripts/login-art/make-card.mjs`), so this version and the fallback version draw the same thing.
 *
 * One per skin: after prerendering, this layer can no longer follow `--ui-accent` the way a live
 * shader does. Six files of a bit over 100 KB each, with the page loading only the current skin's,
 * make up for that cost (same trade-off as `BrandLoop`).
 *
 * Why the loop joins seamlessly: the phases of both blobs of light are **integer multiples** of the
 * frequency of `uLoop` (4 and 3), and `uLoop` going from 0 to 1 returns exactly to the start, so the
 * first and last frames compute to the same image.
 *
 * Fallback: only when the video is **really broken** (decoding unsupported, file can't be fetched)
 * do we fall back to the live shader `BrandGlow`, which has its own CSS fallback in turn. So this
 * area is never blank.
 *
 * "Reduce motion": no autoplay, stay on the first frame: there is an image, and it doesn't move.
 */
import { useEffect, useRef, useState } from "react";
import type { JSX } from "react";
import { BrandGlow } from "./BrandGlow";
import { useSkin } from "../skins/useSkin";
import "./brandGlow.css";

/*
 * Collect with a glob instead of importing one by one: one missing file makes the whole page 500
 * (the file header of `BrandLoop` records that incident).
 * Another benefit: when palettes.ts gets a new skin later, drop the rendered file in and it is
 * picked up, with no change needed here.
 */
const FILES = import.meta.glob<string>("./art/glow-*.mp4", { eager: true, query: "?url", import: "default" });

/**
 * Palette id → loop video for that palette. Keys match the ids in `src/skins/palettes.ts` one to one.
 *
 * This directory holds **portrait only**. The wide version used by the website home page
 * (`glow-wide.mp4`) is in `scripts/login-art/out/`, not here: the glob above is eager, so putting
 * it here would bundle it into the online build, adding 300-odd KB for nothing, while the page
 * would never fetch it.
 */
const LOOPS: Record<string, string> = Object.fromEntries(
  Object.entries(FILES).map(([file, url]) => [/glow-(.+)\.mp4$/.exec(file)?.[1] ?? file, url]),
);

/** `data-skin` is "palette-light/dark"; take the first half */
const paletteOf = (skinId: string) => skinId.replace(/-(dark|light)$/, "");

export function GlowLoop(): JSX.Element {
  const { skinId } = useSkin();
  const [failed, setFailed] = useState(false);
  const video = useRef<HTMLVideoElement>(null);
  const src = LOOPS[paletteOf(skinId)] ?? LOOPS.studio ?? Object.values(LOOPS)[0];

  useEffect(() => {
    const el = video.current;
    if (!el) return;
    const still = typeof matchMedia === "function" && matchMedia("(prefers-reduced-motion: reduce)").matches;
    if (still) { el.pause(); return; }
    /*
     * A rejected play() **does not count as broken**, so here we just swallow it and let canplay try once more.
     * Right after the page loads, or right after a skin change swaps src, the browser often rejects the first
     * call with "play request interrupted by a new load", while the video itself is fine. **2026-10-24 fell
     * right into this**: it used to call setFailed on the first rejection, and after 0.7.28 shipped the live
     * login page kept showing the fallback live shader: the video returned 200 and calling play() by hand
     * also succeeded, only the component's own call was rejected, so it fell back permanently. The only case
     * in which the shader should be brought back is when the media itself reports an error (see onError).
     */
    const tryPlay = () => { void el.play().catch(() => {}); };
    tryPlay();
    el.addEventListener("canplay", tryPlay);
    return () => el.removeEventListener("canplay", tryPlay);
  }, [src]);

  // No video at all (not rendered yet, or trimmed away): use the live shader, leave no blank
  if (failed || !src) return <BrandGlow />;
  return (
    <video
      ref={video}
      className="ps-brand-glow ps-glow-loop"
      data-pc="start-glow-loop"
      src={src}
      loop
      muted
      playsInline
      preload="auto"
      aria-hidden="true"
      // Only the media's own errors count (decoding unsupported, file unavailable); an error event with an empty el.error does not
      onError={(e) => { if (e.currentTarget.error) setFailed(true); }}
    />
  );
}
