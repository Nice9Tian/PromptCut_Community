/**
 * The **finished product** of the aurora in the login page's left rail: a looping video prerendered by
 * PromptCut's own renderer.
 *
 * User decision, 2026-10-24: "the left side is an animation prerendered by the renderer", "use a looping
 * video", "two versions are fine". Measured: one version at 512 wide and CRF 32 is only ~520 KB, and the
 * page loads only the one for the current skin, so we simply made **one per skin** (six). That wins back
 * the only cost of prerendering: the left rail no longer follows `--ui-accent`.
 * The videos are produced in batch by `scripts/login-art/render-all.mjs`, from the same GLSL in
 * `BrandCanvas.tsx` (via the user card generated by `scripts/login-art/make-card.mjs`), so this version
 * and the fallback version draw the same thing.
 *
 * Why the loop is seamless: time in the card runs along a closed circle (`uLoop` goes 0→1 and returns to
 * the start), so frame 0 and frame N come out **byte-for-byte identical**. Measured 2026-10-24: with the
 * project stretched to 49 seconds, exporting frame 0 and frame 1152 separately gives two SHA-256 hashes
 * that match exactly, with zero byte difference.
 *
 * Fallback: only when the video is **really broken** (decoding unsupported, file unavailable) do we fall
 * back to the live shader `BrandCanvas`, which itself has a CSS fallback layer (`BrandAurora`). So this
 * block is never blank at any time.
 *
 * "Reduce motion": no autoplay, stay on the first frame: there is a picture, and it does not move.
 */
import { useEffect, useRef, useState } from "react";
import type { JSX } from "react";
import { BrandCanvas } from "./BrandCanvas";
import { useSkin } from "../skins/useSkin";
import "./brandCanvas.css";

/*
 * Collect with a glob instead of importing one by one: with one file missing the whole page gets a 500
 * (hit on 2026-10-24: the page was first changed to import six, but only one had been rendered at the
 * time, so when the export page loaded the app vite returned a 500 directly and took the batch render
 * down with it).
 * Another benefit of the glob: if palettes.ts gets a new skin later, just drop the rendered file in and
 * it is picked up, with no change needed here.
 */
const FILES = import.meta.glob<string>("./art/login-art-*.mp4", { eager: true, query: "?url", import: "default" });
/** Palette id → the looping video for that set. Keys match the ids in `src/skins/palettes.ts` one to one */
const LOOPS: Record<string, string> = Object.fromEntries(
  Object.entries(FILES).map(([file, url]) => [/login-art-(.+)\.mp4$/.exec(file)?.[1] ?? file, url]),
);

/** `data-skin` is "palette-light/dark"; take the first half */
const paletteOf = (skinId: string) => skinId.replace(/-(dark|light)$/, "");

export function BrandLoop(): JSX.Element {
  const { skinId } = useSkin();
  const [failed, setFailed] = useState(false);
  const video = useRef<HTMLVideoElement>(null);
  const src = LOOPS[paletteOf(skinId)] ?? LOOPS.studio ?? Object.values(LOOPS)[0];

  useEffect(() => {
    const el = video.current;
    if (!el) return;
    const still = typeof matchMedia === "function" && matchMedia("(prefers-reduced-motion: reduce)").matches;
    if (still) { el.pause(); return; }
    /*
     * A rejected play() **does not count as broken**, so here we just swallow it and let canplay try once more.
     * Right after the page loads, or right after a skin change swaps src, the browser often rejects the first
     * call with "play request interrupted by a new load", while the video itself is fine. **2026-10-24 fell
     * right into this**: it used to call setFailed on the first rejection, and after 0.7.28 shipped the live
     * login page kept showing the fallback live shader: the video returned 200 and calling play() by hand
     * also succeeded, only the component's own call was rejected, so it fell back permanently. The only case
     * in which the shader should be brought back is when the media itself reports an error (see onError).
     */
    const tryPlay = () => { void el.play().catch(() => {}); };
    tryPlay();
    el.addEventListener("canplay", tryPlay);
    return () => el.removeEventListener("canplay", tryPlay);
  }, [src]);

  // No video at all (not rendered yet, or trimmed away): use the live shader, leave no blank
  if (failed || !src) return <BrandCanvas />;
  return (
    <video
      ref={video}
      className="ps-brand-loop"
      data-pc="start-brand-loop"
      src={src}
      loop
      muted
      playsInline
      preload="auto"
      aria-hidden="true"
      // Only the media's own errors count (decoding unsupported, file unavailable); an error event with an empty el.error does not
      onError={(e) => { if (e.currentTarget.error) setFailed(true); }}
    />
  );
}
