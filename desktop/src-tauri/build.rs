/// 产品声明里的账号云端(`server/auth/product.mjs` 同一约定):闭源目录有 `product.config.json` 就用它,
/// 公开版没有,这里是空串,外壳不绑任何账号云端。
fn account_cloud_origin() -> String {
    println!("cargo:rerun-if-env-changed=PROMPTCUT_CLOUD_DIR");
    let cloud_dir = std::env::var("PROMPTCUT_CLOUD_DIR").map(std::path::PathBuf::from)
        .unwrap_or_else(|_| std::path::Path::new("../../cloud").to_path_buf());
    let declaration = cloud_dir.join("product.config.json");
    println!("cargo:rerun-if-changed={}", declaration.display());
    let Ok(text) = std::fs::read_to_string(&declaration) else { return String::new() };
    let value: serde_json::Value = serde_json::from_str(&text).expect("product.config.json 不是合法的 JSON");
    value["accountCloudOrigin"].as_str().unwrap_or("").to_string()
}

fn main() {
    println!("cargo:rustc-env=PROMPTCUT_ACCOUNT_CLOUD_ORIGIN={}", account_cloud_origin());
    // Tauri 2 的应用自定义命令默认**不放行**:得在这里登记,tauri-build 会生成
    // permissions/autogenerated/ 下的 allow-<命令> 权限,再由 capabilities/default.json 引用。
    // 没登记的命令前端 invoke 时报「not allowed. Plugin not found」—— 三个 proc_lock 命令
    // 以前就是这么静默失败的(前端那边 catch 掉了,所以没人发现)。
    tauri_build::try_build(
        tauri_build::Attributes::new().app_manifest(tauri_build::AppManifest::new().commands(&[
            "account_bridge",
            "acquire_proc_lock",
            "release_proc_lock",
            "is_proc_locked",
            "desktop_titlebar_command",
            "agent_webview_show",
            "agent_webview_hide",
            "agent_webview_mute",
            "agent_webview_info",
            "menu_bar_color",
        ])),
    )
    .expect("tauri-build 失败");
}
