/// The account cloud in the product declaration (same convention as `server/auth/product.mjs`): use `product.config.json` if the closed-source directory has one,
/// the public edition does not, so this is an empty string and the shell binds to no account cloud.
fn account_cloud_origin() -> String {
    println!("cargo:rerun-if-env-changed=PROMPTCUT_CLOUD_DIR");
    let cloud_dir = std::env::var("PROMPTCUT_CLOUD_DIR").map(std::path::PathBuf::from)
        .unwrap_or_else(|_| std::path::Path::new("../../cloud").to_path_buf());
    let declaration = cloud_dir.join("product.config.json");
    println!("cargo:rerun-if-changed={}", declaration.display());
    let Ok(text) = std::fs::read_to_string(&declaration) else { return String::new() };
    let value: serde_json::Value = serde_json::from_str(&text).expect("product.config.json is not valid JSON");
    value["accountCloudOrigin"].as_str().unwrap_or("").to_string()
}

fn main() {
    println!("cargo:rustc-env=PROMPTCUT_ACCOUNT_CLOUD_ORIGIN={}", account_cloud_origin());
    // Tauri 2 app custom commands are **not allowed by default**: they must be registered here, and tauri-build will generate
    // the allow-<command> permissions under permissions/autogenerated/, which capabilities/default.json then references.
    // For a command that is not registered, the frontend invoke reports "not allowed. Plugin not found": the three proc_lock commands
    // used to fail silently exactly this way (the frontend caught it, so nobody noticed).
    tauri_build::try_build(
        tauri_build::Attributes::new().app_manifest(tauri_build::AppManifest::new().commands(&[
            "account_bridge",
            "acquire_proc_lock",
            "release_proc_lock",
            "is_proc_locked",
            "desktop_titlebar_command",
            "agent_webview_show",
            "agent_webview_hide",
            "agent_webview_mute",
            "agent_webview_info",
            "menu_bar_color",
        ])),
    )
    .expect("tauri-build failed");
}
