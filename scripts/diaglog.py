#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
A tool for taking apart and reading PromptCut chat diagnostic reports.

The diagnostic report ("PromptCut conversation debug v2", generated by conversationReport in src/ai/debug.ts) is one single
JSON. A long chat easily runs to a megabyte or two and over thirty thousand lines: the parts / tools / trace of a single reply alone can take up several hundred thousand characters, and a direct Read
only shows the environment snapshot at the start; the second half, where things actually went wrong, cannot be reached at all. Here it is split into a shape that can be read bite by bite:

  - Command line: overview, anomalies, read by page, read by message, search, split the whole report into small files
  - Python object: load() returns a Report, from which an agent fetches page by page and message by message in a script

Standard library only, Python 3.9+. On Windows use `py -3` (the python in Git Bash is the Store placeholder).

Command line (the report path goes before the subcommand; the path can also be the folder holding the report):

  py -3 scripts/diaglog.py <report> overview            one line per message: role, model, outcome, duration, tool count/failure count, cost
  py -3 scripts/diaglog.py <report> anomalies           errors, failed tools (grouped by reason), fallback retries, long stretches with no events
  py -3 scripts/diaglog.py <report> pages [--size N]    page index: which messages each page covers
  py -3 scripts/diaglog.py <report> page 3 [--size N]   read page 3 (12000 characters per page by default)
  py -3 scripts/diaglog.py <report> show 15 [--part summary|text|timeline|tools|trace|meta] [--page N]
  py -3 scripts/diaglog.py <report> find ENAMETOOLONG [-i] [--limit 50]
  py -3 scripts/diaglog.py <report> env [key]           environment snapshot (without a key it only lists which sections exist)
  py -3 scripts/diaglog.py <report> split [-o dir]      split into small files, by default next to the report in "<report name>.split"

Python:

  import sys; sys.path.insert(0, r"C:\\Users\\admin\\Documents\\PromptCut\\scripts")
  from diaglog import load
  r = load(r"...\\chat-diagnostics-xxx.txt")
  print(r.overview())
  print(r.page_count(), r.page(1))          # read page by page, page numbers start from 1
  m = r[15]                                 # message 15 (same index as messages in the report, negative indexes supported)
  m.error, m.failed_tools, m.tool_counts
  print(m.timeline()); print(m.trace_text())
  for h in r.find("spawn"): print(h)       # each hit carries its page number, then read the context with r.page(h.page)
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
from collections import Counter
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Optional

PAGE_SIZE = 12000
INPUT_PREVIEW = 240
SPLIT_MARKER = ".diaglog-split"

# Tool failures are grouped by reason. "Permission denied" refers specifically to the built-in tools of Claude Code / agy being blocked when running unattended.
# Such failures have nothing to do with whether the tool itself is broken, and must be looked at separately from real errors when investigating.
DENIED = re.compile(
    r"requested permissions|requires approval|haven't granted|permission denied|"
    r"This Bash command contains|Contains simple_expansion|Command contains|refused", re.I)
TIMEOUT = re.compile(r"no response for over\s*\d+\s*seconds|timed? ?out|timeout", re.I)
NOTABLE_STATUS = re.compile(r"retry|fail|denied|interrupt|exceed|truncat|error", re.I)


# ───────────────────────── Small utilities ─────────────────────────

def _ts(v: Any) -> Optional[datetime]:
    """Millisecond timestamp or ISO string → UTC datetime"""
    if v is None:
        return None
    if isinstance(v, (int, float)):
        return datetime.fromtimestamp(v / 1000, tz=timezone.utc)
    try:
        return datetime.fromisoformat(str(v).replace("Z", "+00:00"))
    except ValueError:
        return None


def _hms(dt: Optional[datetime]) -> str:
    return dt.strftime("%H:%M:%S") if dt else "--:--:--"


def _dur(sec: Optional[float]) -> str:
    if sec is None:
        return "-"
    sec = int(sec)
    if sec >= 3600:
        return f"{sec // 3600}h{sec % 3600 // 60:02d}m"
    return f"{sec // 60}m{sec % 60:02d}s"


def _str(v: Any) -> str:
    return v if isinstance(v, str) else json.dumps(v, ensure_ascii=False)


def _clip(v: Any, n: int) -> str:
    s = _str(v).replace("\r", "")
    return s if len(s) <= n else s[:n] + f"…(+{len(s) - n})"


def _one_line(v: Any, n: int) -> str:
    return _clip(v, n).replace("\n", " ⏎ ")


def classify_failure(tool: dict) -> str:
    text = _str(tool.get("summary") or "")
    if DENIED.search(text):
        return "permission denied"
    if TIMEOUT.search(text):
        return "timeout"
    return "error"


def _promptcut_tool_names() -> set:
    """Read the PromptCut tool names from server/mcp-tools.mjs in the repo; when the script has been copied away on its own they cannot be read, and only the mcp__ prefix is recognized"""
    src = Path(__file__).resolve().parent.parent / "server" / "mcp-tools.mjs"
    try:
        return set(re.findall(r"^\s*name:\s*[\"'](\w+)[\"']", src.read_text(encoding="utf-8"), re.M))
    except OSError:
        return set()


PROMPTCUT_TOOLS = _promptcut_tool_names()


def tool_origin(name: str) -> str:
    """Whether it is a PromptCut tool or one built into the CLI (Read / Bash / Skill / grep_search of agy …).
    The claude route carries the mcp__promptcut__ prefix and the agy route uses bare names, so both must be recognized."""
    n = name or ""
    return "PromptCut" if n.startswith("mcp__") or n in PROMPTCUT_TOOLS else "built-in"


def paginate(text: str, size: int = PAGE_SIZE) -> list[str]:
    """Split into pages by line, and hard-split a single line that is too long. For output like show where a single item is already large."""
    pages, cur, cur_len = [], [], 0
    for line in text.splitlines():
        pieces = [line[k:k + size] for k in range(0, len(line), size)] or [""]
        for piece in pieces:
            if cur and cur_len + len(piece) + 1 > size:
                pages.append("\n".join(cur))
                cur, cur_len = [], 0
            cur.append(piece)
            cur_len += len(piece) + 1
    if cur:
        pages.append("\n".join(cur))
    return pages or [""]


# ───────────────────────── One message ─────────────────────────

class Message:
    """One entry of messages[] in the report. raw is the original dict, and commonly used fields are made into properties."""

    def __init__(self, index: int, raw: dict):
        self.index = index
        self.raw = raw

    def __repr__(self) -> str:
        return (f"<Message #{self.index} {self.role} {self.model} {self.outcome or ''} "
                f"tools={len(self.tools)} failed={len(self.failed_tools)}>")

    # Basic fields
    @property
    def role(self) -> str: return self.raw.get("role", "?")
    @property
    def text(self) -> str: return self.raw.get("text") or ""
    @property
    def outcome(self) -> Optional[str]: return self.raw.get("outcome")
    @property
    def runtime(self) -> dict: return self.raw.get("runtime") or {}
    @property
    def usage(self) -> dict: return self.raw.get("usage") or {}
    @property
    def parts(self) -> list: return self.raw.get("parts") or []
    @property
    def tools(self) -> list: return self.raw.get("tools") or []
    @property
    def trace(self) -> list: return self.raw.get("trace") or []
    @property
    def statuses(self) -> list: return self.raw.get("statuses") or []
    @property
    def attachments(self) -> list: return self.raw.get("attachments") or []

    @property
    def error(self) -> Optional[str]:
        e = self.raw.get("error")
        return None if e is None else _str(e)

    @property
    def model(self) -> str:
        return "/".join(str(x) for x in (self.runtime.get("provider"), self.runtime.get("model")) if x)

    @property
    def cost(self) -> Optional[float]: return self.usage.get("total_cost_usd")
    @property
    def started(self) -> Optional[datetime]: return _ts(self.raw.get("startedAt"))
    @property
    def finished(self) -> Optional[datetime]: return _ts(self.raw.get("finishedAt"))

    @property
    def duration(self) -> Optional[float]:
        if self.started and self.finished:
            return (self.finished - self.started).total_seconds()
        return None

    @property
    def failed_tools(self) -> list[tuple[int, dict, str]]:
        """[(index in tools, tool record, reason)], where the reason is permission denied / timeout / error"""
        return [(i, t, classify_failure(t)) for i, t in enumerate(self.tools) if t.get("ok") is False]

    @property
    def tool_counts(self) -> Counter:
        return Counter(t.get("name", "?") for t in self.tools)

    def meta(self) -> dict:
        """The meta information after the big arrays are removed, plus the length of each array"""
        m = {k: v for k, v in self.raw.items() if k not in ("parts", "tools", "trace", "text")}
        m["_counts"] = {"text_chars": len(self.text), "parts": len(self.parts), "tools": len(self.tools),
                        "failed_tools": len(self.failed_tools), "trace": len(self.trace)}
        return m

    # Rendering
    def header(self) -> str:
        bits = [f"#{self.index} {self.role}"]
        if self.model:
            bits.append(self.model)
        if self.outcome:
            bits.append(self.outcome)
        if self.started:
            bits.append(f"{_hms(self.started)}→{_hms(self.finished)} UTC ({_dur(self.duration)})")
        if self.tools:
            bits.append(f"tools {len(self.tools)} (failed {len(self.failed_tools)})")
        if self.cost is not None:
            bits.append(f"${self.cost:.2f}")
        return "## " + " · ".join(bits)

    def timeline(self, input_chars: int = INPUT_PREVIEW) -> str:
        """In order of occurrence: statuses (consecutive repeats are folded into ×N), what was said along the way, every tool call and its result"""
        out: list[str] = []
        tool_no = 0
        last_status, repeat = None, 0

        def flush() -> None:
            nonlocal repeat
            if repeat > 1:
                out[-1] += f"  ×{repeat}"
            repeat = 0

        src = self.parts or [{"kind": "tool", **t} for t in self.tools]
        for p in src:
            kind = p.get("kind") or p.get("type")
            if kind == "status":
                txt = p.get("text", "")
                if txt == last_status:
                    repeat += 1
                    continue
                flush()
                out.append(f"  · Status: {txt}")
                last_status, repeat = txt, 1
                continue
            flush()
            last_status = None
            if kind == "tool":
                tool_no += 1
                ok = p.get("ok")
                mark = "✓" if ok else ("✗" if ok is False else "…")
                line = f"  ▶ [{tool_no}] {p.get('name', '?')} {mark} {_one_line(p.get('input', ''), input_chars)}"
                if ok is False:
                    line += f"  [{classify_failure(p)}]"
                out.append(line)
                if p.get("summary"):
                    out.append(f"      → {_one_line(p['summary'], input_chars)}")
            elif kind == "text":
                t = (p.get("text") or "").strip()
                if t:
                    out.extend("  │ " + ln for ln in t.splitlines())
            elif kind == "thinking":
                t = (p.get("text") or "").strip()
                if t:
                    out.append(f"  (thinking) {_one_line(t, input_chars)}")
            else:
                out.append(f"  ? {kind}: {_one_line(p, input_chars)}")
        flush()
        return "\n".join(out)

    def trace_text(self, gap: float = 60, chars: int = INPUT_PREVIEW) -> str:
        """Execution events are listed one by one with their time; consecutive thinking events are folded into one line; if two events are more than gap seconds apart, a "silence" line is added"""
        out: list[str] = []
        prev: Optional[datetime] = None
        think_n, think_c, think_at = 0, 0, None

        def flush_think() -> None:
            nonlocal think_n, think_c
            if think_n:
                out.append(f"{_hms(think_at)}  thinking    ×{think_n} (total {think_c} chars)")
            think_n, think_c = 0, 0

        for e in self.trace:
            at = _ts(e.get("at"))
            ev = e.get("event") or {}
            if prev and at and (at - prev).total_seconds() >= gap:
                flush_think()
                out.append(f"          … silence {_dur((at - prev).total_seconds())}")
            prev = at or prev
            t = ev.get("type", "?")
            if t == "thinking":
                if not think_n:
                    think_at = at
                think_n += 1
                think_c += len(ev.get("delta") or "")
                continue
            flush_think()
            if t == "text":
                s = _one_line(ev.get("delta", ""), chars)
            elif t == "tool_call":
                s = f"{ev.get('name')} {_one_line(ev.get('input', ''), chars)}"
            elif t == "tool_result":
                s = f"{ev.get('name')} {'✓' if ev.get('ok') else '✗'} {_one_line(ev.get('summary', ''), chars)}"
            else:
                s = _one_line({k: v for k, v in ev.items() if k != "type"}, chars)
            out.append(f"{_hms(at)}  {t:<11} {s}")
        flush_think()
        if self.raw.get("traceTruncated"):
            out.append("(the trace was already truncated when recorded: more than 2000 entries or 1.5MB)")
        return "\n".join(out)

    def trace_gaps(self, gap: float = 120) -> list[tuple[datetime, float, str]]:
        """[(silence start time, seconds, last event before the silence)], from longest to shortest"""
        res, prev, prev_desc = [], None, ""
        for e in self.trace:
            at = _ts(e.get("at"))
            ev = e.get("event") or {}
            if prev and at and (at - prev).total_seconds() >= gap:
                res.append((prev, (at - prev).total_seconds(), prev_desc))
            if ev.get("type") != "thinking":
                prev_desc = f"{ev.get('type')} {ev.get('name') or ''}".strip()
            prev = at or prev
        return sorted(res, key=lambda x: -x[1])

    def render(self, input_chars: int = INPUT_PREVIEW) -> str:
        """One section in the paged document: title, attachments, content, timeline, error"""
        lines = [self.header()]
        if self.attachments:
            lines.append(f"Attachments: {_one_line(self.attachments, 400)}")
        text_parts = "".join(p.get("text") or "" for p in self.parts if p.get("kind") == "text")
        timeline = self.timeline(input_chars) if (self.parts or self.tools) else ""
        # The text in parts is what this reply said; only when they do not match (old format or only the final reply) is a separate section added
        if self.text.strip() and self.text.strip()[:200] not in text_parts:
            lines += ["[Reply text]" if self.role == "assistant" else "[Content]", self.text.rstrip()]
        if timeline:
            lines += ["[Process]", timeline]
        if self.error:
            lines.append(f"!! Error: {self.error}")
        return "\n".join(lines) + "\n"


# ───────────────────────── Pages and search results ─────────────────────────

@dataclass
class Page:
    no: int
    total: int
    lines: list[tuple[str, Optional[int]]] = field(default_factory=list)  # (text, which message it belongs to)

    @property
    def text(self) -> str:
        return "\n".join(t for t, _ in self.lines)

    @property
    def msgs(self) -> list[int]:
        return sorted({o for _, o in self.lines if o is not None})

    def span(self) -> str:
        m = self.msgs
        if not m:
            return "overview"
        return f"message #{m[0]}" if m[0] == m[-1] else f"messages #{m[0]}–#{m[-1]}"


@dataclass
class Hit:
    msg: Optional[int]      # None = environment snapshot
    where: str              # text / error / tool[3] Bash / trace[120] status / environment …
    snippet: str
    page: int
    count: int              # how many times this spot was hit in total

    def __str__(self) -> str:
        who = "environment" if self.msg is None else f"#{self.msg}"
        more = f" ({self.count} hits here)" if self.count > 1 else ""
        return f"[p{self.page}] {who} {self.where}{more}: …{self.snippet}…"


# ───────────────────────── The whole report ─────────────────────────

class Report:
    def __init__(self, path: Path, data: dict):
        self.path = Path(path)
        self.data = data
        self.messages = [Message(i, m) for i, m in enumerate(data.get("messages") or [])]
        self._doc: Optional[list[tuple[str, Optional[int]]]] = None
        self._pages: dict[int, list[Page]] = {}

    def __repr__(self) -> str:
        return f"<Report {self.path.name} {len(self.messages)} messages>"

    def __len__(self) -> int:
        return len(self.messages)

    def __getitem__(self, i: int) -> Message:
        return self.messages[i]

    @property
    def format(self) -> str: return self.data.get("format", "?")
    @property
    def exported_at(self) -> str: return self.data.get("exportedAt", "?")
    @property
    def provider(self) -> Optional[str]: return self.data.get("provider")
    @property
    def runtime(self) -> dict: return self.data.get("runtime") or {}
    @property
    def environment(self) -> Any: return self.data.get("environment")

    # Overview
    def overview(self) -> str:
        size = self.path.stat().st_size / 1e6 if self.path.exists() else 0
        lines = [f"# {self.path.name}",
                 f"format {self.format} · exported {self.exported_at} · {len(self.messages)} messages · {size:.1f} MB"]
        if self.runtime.get("summary"):
            lines.append(f"Config: {self.runtime['summary']}")
            for r in self.runtime.get("used") or []:
                lines.append(f"  - {r.get('description') or _one_line(r, 200)}")
        env = self.environment if isinstance(self.environment, dict) else {}
        proj = env.get("project") or {}
        if proj.get("name"):
            lines.append(f"Project: {proj['name']} · {proj.get('clipCount', '?')} clips · "
                         f"{(env.get('media') or {}).get('count', '?')} media items")
        lines += ["", "| # | Role | Model | Outcome | Start (UTC) | Duration | Tools (failed) | Cost | Content / error |",
                  "|---|---|---|---|---|---|---|---|---|"]
        total = 0.0
        for m in self.messages:
            total += m.cost or 0
            content = ("!! " + m.error) if m.error else m.text
            cells = [f"{m.index}", m.role, m.model or "", m.outcome or "", _hms(m.started) if m.started else "",
                     _dur(m.duration) if m.duration is not None else "",
                     f"{len(m.tools)}({len(m.failed_tools)})" if m.tools else "",
                     f"${m.cost:.2f}" if m.cost is not None else "",
                     _one_line(content, 70).replace("|", "\\|")]
            lines.append("| " + " | ".join(cells) + " |")
        if total:
            lines.append(f"\nTotal recorded cost ${total:.2f} (only replies that ended normally carry usage)")
        return "\n".join(lines)

    # Anomalies
    def anomalies(self) -> list[dict]:
        items: list[dict] = []
        for m in self.messages:
            if m.error:
                items.append({"msg": m.index, "kind": "message error", "detail": m.error})
            groups: dict[tuple[str, str], Counter] = {}
            for _, t, reason in m.failed_tools:
                name = t.get("name", "?")
                groups.setdefault((reason, tool_origin(name)), Counter())[name] += 1
            for (reason, origin), names in groups.items():
                items.append({"msg": m.index, "kind": f"tool {reason} ({origin})",
                              "detail": f"{sum(names.values())} times: " + ", ".join(f"{k}×{v}" for k, v in names.items())})
            for s in dict.fromkeys(s for s in m.statuses if NOTABLE_STATUS.search(s)):
                items.append({"msg": m.index, "kind": "status", "detail": s})
            if m.raw.get("traceTruncated"):
                items.append({"msg": m.index, "kind": "trace truncated", "detail": f"{len(m.trace)} entries / {m.raw.get('traceBytes')} bytes"})
            for start, sec, before in m.trace_gaps()[:3]:
                items.append({"msg": m.index, "kind": "long stretch with no events",
                              "detail": f"from {_hms(start)} for {_dur(sec)}, the last event before it was {before}"})
        return items

    def anomalies_text(self) -> str:
        items = self.anomalies()
        if not items:
            return "No anomalies found."
        lines, cur = [], None
        for it in items:
            if it["msg"] != cur:
                cur = it["msg"]
                lines.append(f"\n{self.messages[cur].header()}")
            lines.append(f"  - [{it['kind']}] {it['detail']}")
        # Check whether each errored reply and each normally completed reply had "built-in tool denied" cases. The fallback retry is triggered by exactly this
        lines.append("\nReply outcome × number of built-in tool denials:")
        for m in self.messages:
            if m.role != "assistant" or not m.tools:
                continue
            denied = sum(1 for _, t, r in m.failed_tools if r == "permission denied" and tool_origin(t.get("name", "")) == "built-in")
            lines.append(f"  #{m.index:<3} {m.outcome or '?':<10} denied {denied}")
        return "\n".join(lines).lstrip("\n")

    # Paging
    def _document(self) -> list[tuple[str, Optional[int]]]:
        if self._doc is None:
            doc: list[tuple[str, Optional[int]]] = [(ln, None) for ln in self.overview().splitlines()] + [("", None)]
            for m in self.messages:
                doc += [(ln, m.index) for ln in m.render().splitlines()] + [("", m.index)]
            self._doc = doc
        return self._doc

    def pages(self, size: int = PAGE_SIZE) -> list[Page]:
        if size in self._pages:
            return self._pages[size]
        pages: list[Page] = []
        cur: list[tuple[str, Optional[int]]] = []
        cur_len = 0
        for text, owner in self._document():
            pieces = [text[k:k + size] for k in range(0, len(text), size)] or [""]
            for piece in pieces:
                # Turn the page when it is full; when the page is already past 60% and a new message's title comes up, also turn early, so that a message starts at the top of a page as far as possible
                if cur and (cur_len + len(piece) + 1 > size or (piece.startswith("## #") and cur_len > size * 0.6)):
                    pages.append(Page(len(pages) + 1, 0, cur))
                    cur, cur_len = [], 0
                cur.append((piece, owner))
                cur_len += len(piece) + 1
        if cur:
            pages.append(Page(len(pages) + 1, 0, cur))
        for p in pages:
            p.total = len(pages)
        self._pages[size] = pages
        return pages

    def page_count(self, size: int = PAGE_SIZE) -> int:
        return len(self.pages(size))

    def page(self, n: int, size: int = PAGE_SIZE) -> str:
        pages = self.pages(size)
        if not 1 <= n <= len(pages):
            raise IndexError(f"Page number {n} is out of range, there are {len(pages)} pages in total")
        p = pages[n - 1]
        tail = f"(next page: page {n + 1})" if n < len(pages) else "(last page)"
        return f"=== page {n}/{len(pages)} · {p.span()} ===\n{p.text}\n=== {tail} ==="

    def page_index(self, size: int = PAGE_SIZE) -> str:
        lines = []
        for p in self.pages(size):
            heads = [t for t, _ in p.lines if t.startswith("## #")]
            first = heads[0][3:] if heads else f"(continued from the previous page #{p.msgs[0]})" if p.msgs else "overview"
            lines.append(f"p{p.no:<4} {p.span():<14} {len(p.text):>6} chars  {_one_line(first, 90)}")
        return "\n".join(lines)

    def pages_of(self, msg: int, size: int = PAGE_SIZE) -> list[int]:
        return [p.no for p in self.pages(size) if msg in p.msgs]

    # Search
    def find(self, pattern: str, ignore_case: bool = False, limit: int = 50, size: int = PAGE_SIZE) -> list[Hit]:
        """Search in the raw fields (tool arguments are not truncated); for each spot give the context of the first hit and the page number it is on"""
        rx = re.compile(pattern, re.I if ignore_case else 0)
        pages = self.pages(size)
        hits: list[Hit] = []

        def page_for(msg: Optional[int]) -> int:
            cands = [p for p in pages if (msg in p.msgs if msg is not None else not p.msgs)]
            for p in cands:
                if rx.search(p.text):
                    return p.no
            return cands[0].no if cands else 1

        def add(msg: Optional[int], where: str, value: Any) -> bool:
            s = _str(value)
            found = list(rx.finditer(s))
            if found:
                a, b = max(0, found[0].start() - 80), min(len(s), found[0].end() + 80)
                hits.append(Hit(msg, where, s[a:b].replace("\n", " ⏎ "), page_for(msg), len(found)))
            return len(hits) >= limit

        if self.environment is not None and add(None, "environment", self.environment):
            return hits
        for m in self.messages:
            fields: list[tuple[str, Any]] = [("text", m.text), ("error", m.error or ""), ("attachments", m.attachments)]
            fields += [(f"tool[{i}] {t.get('name')}", t) for i, t in enumerate(m.tools)]
            fields += [(f"status[{i}]", s) for i, s in enumerate(m.statuses)]
            # The tool events in trace duplicate tools and thinking is empty, so only the remaining kinds are searched
            fields += [(f"trace[{i}] {e.get('event', {}).get('type')}", e.get("event"))
                       for i, e in enumerate(m.trace)
                       if (e.get("event") or {}).get("type") not in ("thinking", "tool_call", "tool_result")]
            for where, v in fields:
                if v and add(m.index, where, v):
                    return hits
        return hits

    # Split into small files
    def split(self, out: Optional[Path | str] = None, size: int = PAGE_SIZE) -> Path:
        out = Path(out) if out else self.path.with_name(self.path.stem + ".split")
        if out.exists() and any(out.iterdir()):
            if not (out / SPLIT_MARKER).exists():
                raise FileExistsError(f"{out} already exists and was not produced by this tool, not overwriting")
            shutil.rmtree(out)
        out.mkdir(parents=True, exist_ok=True)

        def w(p: Path, s: str) -> None:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(s, encoding="utf-8")

        def wj(p: Path, o: Any) -> None:
            w(p, json.dumps(o, ensure_ascii=False, indent=2))

        w(out / SPLIT_MARKER, f"{self.path}\n")
        wj(out / "meta.json", {k: v for k, v in self.data.items() if k not in ("messages", "environment")})
        env = self.environment
        if isinstance(env, dict):
            for k, v in env.items():
                safe = re.sub(r'[\\/:*?"<>|]', "_", k)   # before 3.12 an f-string expression cannot contain a backslash
                wj(out / "environment" / f"{safe}.json", v)
        elif env is not None:
            wj(out / "environment.json", env)

        for m in self.messages:
            d = out / "messages" / f"{m.index:02d}-{m.role}"
            wj(d / "meta.json", m.meta())
            if m.text:
                w(d / "text.md", m.text)
            if m.parts or m.tools:
                w(d / "timeline.md", m.header() + "\n\n" + m.timeline(input_chars=2000) + "\n")
            if m.tools:
                w(d / "tools.jsonl", "".join(json.dumps(t, ensure_ascii=False) + "\n" for t in m.tools))
            if m.trace:
                w(d / "trace.md", m.trace_text() + "\n")
                w(d / "trace.jsonl", "".join(json.dumps(e, ensure_ascii=False) + "\n" for e in m.trace))

        for p in self.pages(size):
            w(out / "pages" / f"page-{p.no:03d}.md", self.page(p.no, size) + "\n")
        w(out / "pages" / "index.md", self.page_index(size) + "\n")
        anomalies = self.anomalies_text()
        w(out / "anomalies.md", anomalies + "\n")
        w(out / "README.md", "\n".join([
            self.overview(), "",
            "## Contents", "",
            "- `anomalies.md` errors, failed tools, fallback retries, long stretches with no events",
            f"- `pages/page-NNN.md` the whole chat split in order into {self.page_count(size)} pages of about {size} characters each; `pages/index.md` is the page index",
            "- `messages/NN-role/` a single message: `text.md` the body, `timeline.md` the process (tool arguments truncated to 2000 characters),"
            "`tools.jsonl` the raw tool records, `trace.md` / `trace.jsonl` the timestamped execution events, `meta.json` the remaining fields",
            "- `environment/*.json` the environment snapshot at the moment of export, split by section",
            "- `meta.json` the report header (format, export time, runtime config)",
            "", "## Anomalies", "", anomalies, ""]))
        return out


def load(path: Path | str) -> Report:
    """Read a diagnostic report. path can be the report file or the folder holding the report (the largest .txt / .json inside is taken)."""
    p = Path(path)
    if p.is_dir():
        cands = sorted((f for f in p.iterdir() if f.suffix.lower() in (".txt", ".json") and f.is_file()),
                       key=lambda f: -f.stat().st_size)
        if not cands:
            raise FileNotFoundError(f"No .txt / .json in {p}")
        p = cands[0]
    raw = p.read_bytes().decode("utf-8-sig", errors="replace")   # a BOM is included when saved
    try:
        data = json.loads(raw)
    except json.JSONDecodeError:
        i = raw.find("{")          # for when a few lines of explanatory text were pasted in front of the report
        if i < 0:
            raise
        data = json.loads(raw[i:])
    if not isinstance(data, dict) or not isinstance(data.get("messages"), list):
        raise ValueError(f"{p.name} does not look like a PromptCut chat diagnostic report: there is no messages array at the top level")
    return Report(p, data)


# ───────────────────────── Command line ─────────────────────────

def main(argv: Optional[list[str]] = None) -> int:
    for s in (sys.stdout, sys.stderr):
        try:
            s.reconfigure(encoding="utf-8")
        except Exception:
            pass
    ap = argparse.ArgumentParser(prog="diaglog", description="PromptCut chat diagnostic report splitting and reading tool")
    ap.add_argument("report", help="diagnostic report file, or the folder it is in")
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("overview", help="summary table with one line per message")
    sub.add_parser("anomalies", help="errors, failed tools, fallback retries, long stretches with no events")
    sp = sub.add_parser("pages", help="page index")
    sp.add_argument("--size", type=int, default=PAGE_SIZE)
    sp = sub.add_parser("page", help="read page N")
    sp.add_argument("n", type=int)
    sp.add_argument("--size", type=int, default=PAGE_SIZE)
    sp = sub.add_parser("show", help="view one message")
    sp.add_argument("i", type=int, help="message index, negative values supported")
    sp.add_argument("--part", choices=["summary", "text", "timeline", "tools", "trace", "meta"], default="summary")
    sp.add_argument("--page", type=int, help="when the output is too long, view only page N")
    sp.add_argument("--size", type=int, default=PAGE_SIZE)
    sp = sub.add_parser("find", help="regex search")
    sp.add_argument("pattern")
    sp.add_argument("-i", action="store_true", help="ignore case")
    sp.add_argument("--limit", type=int, default=50)
    sp = sub.add_parser("env", help="environment snapshot")
    sp.add_argument("key", nargs="?")
    sp = sub.add_parser("split", help="split into small files")
    sp.add_argument("-o", "--out")
    sp.add_argument("--size", type=int, default=PAGE_SIZE)
    a = ap.parse_args(argv)

    r = load(a.report)
    if a.cmd == "overview":
        print(r.overview())
    elif a.cmd == "anomalies":
        print(r.anomalies_text())
    elif a.cmd == "pages":
        print(r.page_index(a.size))
    elif a.cmd == "page":
        print(r.page(a.n, a.size))
    elif a.cmd == "show":
        m = r[a.i]
        text = {
            "summary": lambda: m.render(),
            "text": lambda: m.text,
            "timeline": lambda: m.header() + "\n" + m.timeline(input_chars=2000),
            "tools": lambda: "\n".join(json.dumps(t, ensure_ascii=False) for t in m.tools),
            "trace": lambda: m.trace_text() or "(this message has no trace)",
            "meta": lambda: json.dumps(m.meta(), ensure_ascii=False, indent=2),
        }[a.part]()
        chunks = paginate(text, a.size)
        if a.page:
            print(f"=== #{m.index} {a.part} page {a.page}/{len(chunks)} ===\n{chunks[a.page - 1]}")
        else:
            print(text)
            if len(chunks) > 1:
                print(f"\n({len(text)} characters in total; if too long, add --page 1..{len(chunks)} to view by page)", file=sys.stderr)
    elif a.cmd == "find":
        hits = r.find(a.pattern, a.i, a.limit)
        for h in hits:
            print(h)
        print(f"({len(hits)} hits{', limit reached' if len(hits) >= a.limit else ''})", file=sys.stderr)
    elif a.cmd == "env":
        env = r.environment
        if a.key is None:
            if isinstance(env, dict):
                for k, v in env.items():
                    print(f"{k:<16} {len(_str(v)):>7} chars  {_one_line(v, 80) if isinstance(v, str) else ''}")
            else:
                print(_str(env))
        else:
            print(json.dumps((env or {}).get(a.key), ensure_ascii=False, indent=2))
    elif a.cmd == "split":
        out = r.split(a.out, a.size)
        print(f"Split done: {out}\nLook at {out / 'README.md'} first")
    return 0


if __name__ == "__main__":
    sys.exit(main())
